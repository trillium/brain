// The doctor's tallies for the census: a missing wrapper is a warning the
// convergence verbs clear, an orphan is a failure nothing repairs
// automatically (so it lands in FAILING STORES by name).
func TestCensusTallyFailsOnOrphansWarnsOnMissing(t *testing.T) {
	warns, failing := censusTally(wrapperCensus{Registered: 55, MissingWrapper: []string{"newby"}})
	if warns != 1 || len(failing) != 0 {
		t.Errorf("missing wrapper: warns=%d failing=%v, want 1 warning and no failure", warns, failing)
	}
	warns, failing = censusTally(wrapperCensus{Registered: 55, OrphanWrappers: []string{"ghost", "relay"}})
	if warns != 0 || len(failing) != 2 || failing[0] != "ghost" || failing[1] != "relay" {
		t.Errorf("orphans: warns=%d failing=%v, want no warning and both orphans failing", warns, failing)
	}
	warns, failing = censusTally(wrapperCensus{Registered: 55})
	if warns != 0 || len(failing) != 0 {
		t.Errorf("converged host: warns=%d failing=%v, want clean", warns, failing)
	}
}

// The doctor prints the census it computed for the registry the doctor walked,
// so the counts a scheduler reads and the counts an operator reads agree.
func TestDoctorCensusUsesTheRegistryOnThisHost(t *testing.T) {
	home := isolatedHome(t)
	bin := filepath.Join(home, ".local", "bin")
	stub := filepath.Join(home, "bin", "bd-ok")
	writeCensusFile(t, stub, "#!/bin/sh\necho '[]'\nexit 0\n", 0o755)
	writeCensusFile(t, filepath.Join(bin, "task"),
		"#!/bin/sh\nexport BEADS_DIR=\"$HOME/data/task/.beads\"\nexec "+stub+" \"$@\"\n", 0o755)
	beadsDir := filepath.Join(home, "data", "task", ".beads")
	writeCensusFile(t, filepath.Join(beadsDir, "metadata.json"), `{"dolt_mode":"server"}`, 0o600)
	writeCensusFile(t, filepath.Join(bin, "ghost"),
		"#!/bin/sh\n# Auto-generated by 'brain stores create ghost'.\nexit 0\n", 0o755)
	if err := saveStoresRegistry(map[string]storeEntry{
		"task":  {Path: beadsDir},
		"newby": {Path: filepath.Join(home, "data", "newby", ".beads")},
	}); err != nil {
		t.Fatal(err)
	}

	census := censusWrappersAgainstRegistry(mustLoadStoresForTest(t))
	line := census.summary()
	for _, want := range []string{
		"Wrappers: 1/2 registered stores have a wrapper",
		"1 registered with NO wrapper: newby",
		"1 wrapper(s) with NO registry entry: ghost",
	} {
		if !strings.Contains(line, want) {
			t.Errorf("census summary missing %q:\n%s", want, line)
		}
	}
	if warns, failing := censusTally(census); warns != 1 || len(failing) != 1 || failing[0] != "ghost" {
		t.Errorf("tally = %d warns, %v failing; want 1 warn and ghost failing", warns, failing)
	}
}

// mustLoadStoresForTest loads the registry the doctor reads (the scratch HOME).
func mustLoadStoresForTest(t *testing.T) map[string]storeEntry {
	t.Helper()
	stores, err := loadStoresRegistry()
	if err != nil {
		t.Fatalf("loading registry: %v", err)
	}
	return stores
}

// On a client machine the missing-wrapper fix is the client's own install verb:
// generating a local store wrapper there would point the command at a store this
// machine does not serve.
func TestCensusFixNamesTheClientVerbOnAClientMachine(t *testing.T) {
	home, bin := censusHome(t)
	writeCensusFile(t, filepath.Join(home, ".config", "brain", "remote.yaml"), "host: mini1@100.102.238.78\n", 0o600)

	if got := remoteClientHost(); got != "mini1@100.102.238.78" {
		t.Fatalf("remoteClientHost = %q", got)
	}
	c := censusWrappersAgainstRegistry(map[string]storeEntry{"task": {Path: "/data/task/.beads"}})
	fixes := strings.Join(c.fixes(), "\n")
	if !strings.Contains(fixes, "brain remote install") || !strings.Contains(fixes, "client of mini1@100.102.238.78") {
		t.Errorf("client fix line wrong:\n%s", fixes)
	}
	if strings.Contains(fixes, "brain stores rewrite-wrappers") {
		t.Errorf("a client must not be told to generate store wrappers:\n%s", fixes)
	}

	// The boundary note appears only when a client inspects locally.
	if got := localInspectionNote(); got != "" {
		t.Errorf("note should stay quiet while forwarding is active: %q", got)
	}
	t.Setenv(envRemoteOff, "off")
	if got := localInspectionNote(); !strings.Contains(got, "client of mini1@100.102.238.78") || !strings.Contains(got, "THIS machine") {
		t.Errorf("note = %q", got)
	}

	// Nothing was generated by the census, and the wrapper is still absent.
	_ = bin
}

// A client machine never gets a locally generated store wrapper: the store is
// reached through a forwarding wrapper that 'brain remote install' writes.
