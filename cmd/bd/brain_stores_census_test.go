// censusHome builds a scratch ~/.local/bin plus a registry map, so the census
// can be checked without touching a real host.
func censusHome(t *testing.T) (string, string) {
	t.Helper()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	bin := filepath.Join(home, ".local", "bin")
	if err := os.MkdirAll(bin, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	return home, bin
}

func writeCensusFile(t *testing.T, path, body string, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), mode); err != nil {
		t.Fatal(err)
	}
}

// The census partitions the registry by wrapper presence and catches a wrapper
// the registry does not know about. This is the check a read probe cannot make.
func TestCensusWrappersAgainstRegistry(t *testing.T) {
	_, bin := censusHome(t)

	writeCensusFile(t, filepath.Join(bin, "task"),
		"#!/bin/sh\n# Auto-generated by 'brain stores create task'.\nexec bd \"$@\"\n", 0o755)
	// Present but not executable: nothing can reach the store through it.
	writeCensusFile(t, filepath.Join(bin, "inbox"),
		"#!/bin/sh\n# Auto-generated by 'brain stores create inbox'.\nexec bd \"$@\"\n", 0o644)
	// A generated wrapper for a store the registry forgot.
	writeCensusFile(t, filepath.Join(bin, "ghost"),
		"#!/bin/sh\n# Auto-generated by 'brain stores create ghost'.\nexec bd \"$@\"\n", 0o755)
	// A client-mode forwarding wrapper whose store is not registered either.
	writeCensusFile(t, filepath.Join(bin, "relay"),
		"#!/bin/sh\n# brain-remote-wrapper: generated by 'brain remote install'.\nexec brain \"$@\"\n", 0o755)
	// Not ours: a hand-written script that happens to sit next to them.
	writeCensusFile(t, filepath.Join(bin, "notes-dev"), "#!/bin/sh\necho notes\n", 0o755)
	// A backup of a wrapper kept in the bin directory: generated, but not a
	// wrapper, and its store is registered under its plain name.
	writeCensusFile(t, filepath.Join(bin, "task.pre-remote-route-20260924"),
		"#!/bin/sh\n# Auto-generated by 'brain stores create task'.\nexec bd \"$@\"\n", 0o755)
	// A hand-made alias symlink: not a wrapper this tool generated.
	if err := os.Symlink(filepath.Join(bin, "task"), filepath.Join(bin, "tasks")); err != nil {
		t.Fatal(err)
	}

	stores := map[string]storeEntry{
		"task":   {Path: "/data/task/.beads"},
		"inbox":  {Path: "/data/inbox/.beads"},
		"chores": {Path: "/data/chores/.beads"}, // no wrapper at all
	}
	c := censusWrappersAgainstRegistry(stores)

	if c.Registered != 3 {
		t.Errorf("Registered = %d, want 3", c.Registered)
	}
	if len(c.WithWrapper) != 1 || c.WithWrapper[0] != "task" {
		t.Errorf("WithWrapper = %v, want [task]", c.WithWrapper)
	}
	if len(c.MissingWrapper) != 2 {
		t.Fatalf("MissingWrapper = %v, want inbox + chores", c.MissingWrapper)
	}
	if c.MissingWrapper[0] != "chores" || c.MissingWrapper[1] != "inbox (present but not executable)" {
		t.Errorf("MissingWrapper = %v", c.MissingWrapper)
	}
	if len(c.OrphanWrappers) != 2 || c.OrphanWrappers[0] != "ghost" || c.OrphanWrappers[1] != "relay" {
		t.Errorf("OrphanWrappers = %v, want [ghost relay]", c.OrphanWrappers)
	}
	if len(c.BackupWrappers) != 1 || c.BackupWrappers[0] != "task.pre-remote-route-20260924" {
		t.Errorf("BackupWrappers = %v, want the .pre- copy only", c.BackupWrappers)
	}

	line := c.summary()
	for _, want := range []string{"Wrappers: 1/3 registered stores have a wrapper", "2 registered with NO wrapper", "2 wrapper(s) with NO registry entry", "1 backup copy/copies in PATH"} {
		if !strings.Contains(line, want) {
			t.Errorf("summary missing %q:\n%s", want, line)
		}
	}
	fixes := strings.Join(c.fixes(), "\n")
	if strings.Contains(fixes, "task.pre-remote-route") {
		t.Errorf("a backup copy must not be offered for deletion as a wrapper:\n%s", fixes)
	}
	if !strings.Contains(fixes, "move the backup copy/copies out of PATH") {
		t.Errorf("backup copies need their own advice:\n%s", fixes)
	}
	if !strings.Contains(fixes, "brain stores rewrite-wrappers") {
		t.Errorf("missing wrapper has no convergence fix:\n%s", fixes)
	}
	if !strings.Contains(fixes, "brain stores add") || !strings.Contains(fixes, "rm ") {
		t.Errorf("orphans must not be auto-deleted, and must name both commands:\n%s", fixes)
	}
}

// A healthy host reports the counts and nothing else: no missing wrapper, no
// orphan, and the summary says so.
func TestCensusReportsAConvergedHost(t *testing.T) {
	_, bin := censusHome(t)
	writeCensusFile(t, filepath.Join(bin, "task"),
		"#!/bin/sh\n# Auto-generated by 'brain stores create task'.\nexec bd \"$@\"\n", 0o755)
	stores := map[string]storeEntry{"task": {Path: "/data/task/.beads"}}

	c := censusWrappersAgainstRegistry(stores)
	if len(c.MissingWrapper) != 0 || len(c.OrphanWrappers) != 0 {
		t.Fatalf("census = %+v, want clean", c)
	}
	if got := c.summary(); got != "Wrappers: 1/1 registered stores have a wrapper; no orphans" {
		t.Errorf("summary = %q", got)
	}
	if fixes := c.fixes(); len(fixes) != 0 {
		t.Errorf("a clean host needs no fix lines: %v", fixes)
	}

	// An alias wrapper's own name is never a registry key: it binds to a
	// canonical store by BD_NAME, and it is not an orphan while that store is
	// registered ('brain stores alias task tk').
	writeCensusFile(t, filepath.Join(bin, "tk"),
		"#!/bin/sh\n# Auto-generated by 'brain stores alias task tk'.\n# Routes the \"tk\" CLI variant to the \"task\" store.\nexec env BEADS_DIR=/data/task/.beads BD_NAME=\"task\" bd \"$@\"\n", 0o755)
	c = censusWrappersAgainstRegistry(stores)
	if len(c.OrphanWrappers) != 0 {
		t.Errorf("a registered store's alias was reported as an orphan: %v", c.OrphanWrappers)
	}

	// Both wrappers ARE orphans once their store leaves the registry. The
	// alias is judged by the store it binds to, not by its own name.
	c = censusWrappersAgainstRegistry(map[string]storeEntry{})
	if len(c.OrphanWrappers) != 2 || c.OrphanWrappers[0] != "task" || c.OrphanWrappers[1] != "tk" {
		t.Errorf("OrphanWrappers = %v, want [task tk]", c.OrphanWrappers)
	}
}

// A store that is in the registry and already has a canonical wrapper is the
// common case and must not be reported at all.
func TestCensusIgnoresUnrelatedScriptsInBin(t *testing.T) {
	_, bin := censusHome(t)
	for _, name := range []string{"bd", "brain", "dolt", "some-tool", "llm-task"} {
		writeCensusFile(t, filepath.Join(bin, name), "#!/bin/sh\nexit 0\n", 0o755)
	}
	c := censusWrappersAgainstRegistry(map[string]storeEntry{})
	if len(c.OrphanWrappers) != 0 {
		t.Errorf("hand-written scripts were reported as store wrappers: %v", c.OrphanWrappers)
	}
}

