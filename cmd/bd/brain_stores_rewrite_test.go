func TestShellPathExpr(t *testing.T) {
	t.Setenv("HOME", "/home/u")
	for in, want := range map[string]string{
		"/home/u/data/x/.beads": `"$HOME/data/x/.beads"`,
		"/home/u":               `"$HOME"`,
		"/home/u/a$b":           `"$HOME/a\$b"`,
		"/home/user/x":          `"/home/user/x"`, // prefix of a sibling, not under home
		"/data/x":               `"/data/x"`,
	} {
		if got := shellPathExpr(in); got != want {
			t.Errorf("shellPathExpr(%q) = %s, want %s", in, got, want)
		}
	}
}

// writeScratchStoreHostRecord gives a scratch HOME the one store-host record a
// server-mode wrapper reads at run time, so a converged wrapper can actually
// resolve a database in a test.
func writeScratchStoreHostRecord(t *testing.T, home string) string {
	t.Helper()
	path := filepath.Join(home, ".config", "brain", "store-host.env")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte("BEADS_DOLT_SERVER_HOST=127.0.0.1\nBEADS_DOLT_SERVER_PORT=3307\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

// Existing wrappers are patched in place: only home paths change, hand-added
// env survives, alias wrappers are covered, and a registered store with no
// wrapper gets the canonical one.
func TestRewriteAllStoreWrappersVerifiesEach(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	binDir := t.TempDir()
	writeExec(t, filepath.Join(binDir, "bd"), "#!/bin/sh\n[ -d \"$BEADS_DIR\" ] || { echo \"no database at $BEADS_DIR\" >&2; exit 1; }\n")
	t.Setenv("PATH", binDir+":"+os.Getenv("PATH"))

	good := filepath.Join(home, "data", "good", ".beads")
	if err := os.MkdirAll(good, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	stores := map[string]storeEntry{
		"good":   {Path: good},
		"gone":   {Path: filepath.Join(home, "data", "gone", ".beads")},
		"nowrap": {Path: good},
	}
	wdir := filepath.Join(home, ".local", "bin")
	if err := os.MkdirAll(wdir, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	writeExec(t, filepath.Join(wdir, "good"), "#!/bin/sh\nexport BEADS_DIR=/Users/someone/data/good/.beads\nexport BRAIN_KNOWLEDGE_ROOT=\"/Users/someone/data/good\"\nexport BRAIN_EXFIL_FLAT=1\nexport CUSTOM_PIN=keepme\nexec bd \"$@\"\n")
	writeExec(t, filepath.Join(wdir, "gone"), "#!/bin/sh\nexec env BEADS_DIR=\""+filepath.Join(home, "data", "gone", ".beads")+"\" BD_NAME=gone bd \"$@\"\n")
	writeExec(t, filepath.Join(wdir, "gd"), "#!/bin/sh\n# Auto-generated by 'brain stores alias good gd'.\nexec env BEADS_DIR=\"/Users/someone/data/good/.beads\" BD_NAME=\"good\" bd \"$@\"\n")
	writeExec(t, filepath.Join(wdir, "unrelated"), "#!/bin/sh\nexport BEADS_DIR=/Users/someone/x\n")

	res := rewriteAllStoreWrappers(rewriteRunOptions{self: "bd", stores: stores, jobs: 2, timeout: 10 * time.Second, backup: true})
	byName := map[string]wrapperRewrite{}
	for _, r := range res {
		byName[r.Name] = r
	}
	if byName["good"].Status != "ok" || byName["gd"].Status != "ok" {
		t.Errorf("good/gd should verify: %+v %+v", byName["good"], byName["gd"])
	}
	if byName["gone"].Status != "fail" || !strings.Contains(byName["gone"].Reason, "no database") {
		t.Errorf("gone should fail loudly: %+v", byName["gone"])
	}
	// A registered store whose wrapper is missing gets one generated.
	if byName["nowrap"].Status != "ok" || !byName["nowrap"].Generated {
		t.Errorf("nowrap should be generated and verify: %+v", byName["nowrap"])
	}
	if _, err := os.Stat(filepath.Join(wdir, "nowrap")); err != nil {
		t.Errorf("wrapper was not generated for a store that had none: %v", err)
	}
	if _, ok := byName["unrelated"]; ok {
		t.Errorf("non-store script must be left alone")
	}
	for _, n := range []string{"good", "gd", "nowrap"} {
		body, _ := os.ReadFile(filepath.Join(wdir, n))
		if strings.Contains(string(body), "/Users/someone") || strings.Contains(string(body), home) {
			t.Errorf("%s not rewritten home-relative:\n%s", n, body)
		}
		if !strings.Contains(string(body), `BEADS_DIR="$HOME/data/good/.beads"`) {
			t.Errorf("%s BEADS_DIR wrong:\n%s", n, body)
		}
	}
	body, _ := os.ReadFile(filepath.Join(wdir, "good"))
	for _, want := range []string{`BRAIN_KNOWLEDGE_ROOT="$HOME/data/good"`, "BRAIN_EXFIL_FLAT=1", "CUSTOM_PIN=keepme", `exec bd "$@"`} {
		if !strings.Contains(string(body), want) {
			t.Errorf("good lost %q:\n%s", want, body)
		}
	}
	if f := failedRewrites(res); len(f) != 1 || f[0].Name != "gone" {
		t.Errorf("failedRewrites = %+v", f)
	}
}

// Every wrapper this verb changes is backed up first, and a rewritten
// server-mode wrapper stops pinning a host so the shared record wins.
func TestRewriteBacksUpAndDropsBakedHostPin(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	binDir := t.TempDir()
	writeExec(t, filepath.Join(binDir, "bd"), "#!/bin/sh\n[ -d \"$BEADS_DIR\" ] || { echo \"no database at $BEADS_DIR\" >&2; exit 1; }\n")
	t.Setenv("PATH", binDir+":"+os.Getenv("PATH"))
	t.Setenv(configfile.StoreHostFileEnvVar, writeScratchStoreHostRecord(t, home))

	beadsDir := filepath.Join(home, "data", "task", ".beads")
	if err := os.MkdirAll(beadsDir, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(beadsDir, "metadata.json"),
		[]byte(`{"dolt_mode":"server","dolt_database":"brain_unified"}`), 0o600); err != nil {
		t.Fatal(err)
	}
	wdir := filepath.Join(home, ".local", "bin")
	if err := os.MkdirAll(wdir, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	wrapper := filepath.Join(wdir, "task")
	original := "#!/bin/sh\nexport BEADS_DIR=\"/Users/someone/data/task/.beads\"\nexport BEADS_DOLT_SERVER_HOST=127.0.0.1\nexport BEADS_DOLT_SERVER_PORT=3307\nexec bd \"$@\"\n"
	writeExec(t, wrapper, original)

	res := rewriteAllStoreWrappers(rewriteRunOptions{
		self: "bd", stores: map[string]storeEntry{"task": {Path: beadsDir}}, jobs: 1, timeout: 10 * time.Second, backup: true,
	})
	if len(res) != 1 || res[0].Status != "ok" {
		t.Fatalf("rewrite result = %+v", res)
	}
	if !res[0].Repointed || !res[0].Changed {
		t.Errorf("baked pin should mark the wrapper repointed: %+v", res[0])
	}
	body, err := os.ReadFile(wrapper)
	if err != nil {
		t.Fatal(err)
	}
	if _, removed := stripBakedServerPins(string(body)); removed {
		t.Errorf("baked host pin survived:\n%s", body)
	}
	if strings.Contains(string(body), "export BEADS_DOLT_SERVER_HOST=127.0.0.1") {
		t.Errorf("the literal pin value survived:\n%s", body)
	}
	if !strings.Contains(string(body), "_store_host_file=") {
		t.Errorf("shared host block missing:\n%s", body)
	}
	if res[0].Backup == "" {
		t.Fatalf("no backup recorded: %+v", res[0])
	}
	backed, err := os.ReadFile(res[0].Backup)
	if err != nil {
		t.Fatalf("backup unreadable: %v", err)
	}
	if string(backed) != original {
		t.Errorf("backup is not the previous wrapper:\n%s", backed)
	}
	if !strings.Contains(res[0].Backup, filepath.Join(".local", "state", "brain", "wrapper-backups")) {
		t.Errorf("backup outside the state dir: %s", res[0].Backup)
	}
}

// --dry-run reports what would change and writes nothing: no wrapper, no
// backup, and it still reads each wrapper through so the report is real.
func TestRewriteDryRunWritesNothing(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	binDir := t.TempDir()
	writeExec(t, filepath.Join(binDir, "bd"), "#!/bin/sh\n[ -d \"$BEADS_DIR\" ] || { echo \"no database at $BEADS_DIR\" >&2; exit 1; }\n")
	t.Setenv("PATH", binDir+":"+os.Getenv("PATH"))
	t.Setenv(configfile.StoreHostFileEnvVar, writeScratchStoreHostRecord(t, home))

	beadsDir := filepath.Join(home, "data", "task", ".beads")
	if err := os.MkdirAll(beadsDir, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(beadsDir, "metadata.json"),
		[]byte(`{"dolt_mode":"server","dolt_database":"brain_unified"}`), 0o600); err != nil {
		t.Fatal(err)
	}
	stores := map[string]storeEntry{"task": {Path: beadsDir}, "missing": {Path: filepath.Join(home, "data", "missing", ".beads")}}
	res := rewriteAllStoreWrappers(rewriteRunOptions{
		self: "bd", stores: stores, jobs: 2, timeout: 10 * time.Second, dryRun: true, backup: true,
	})
	byName := map[string]wrapperRewrite{}
	for _, r := range res {
		byName[r.Name] = r
	}
	if !byName["task"].DryRun || !byName["task"].Generated || !byName["task"].WouldWrite {
		t.Errorf("dry run should report the generation it would do: %+v", byName["task"])
	}
	if byName["missing"].Status != "fail" || !strings.Contains(byName["missing"].Reason, "no store directory") {
		t.Errorf("a store with no directory cannot be generated: %+v", byName["missing"])
	}
	if _, err := os.Stat(filepath.Join(home, ".local", "bin", "task")); err == nil {
		t.Error("dry run wrote a wrapper")
	}
	if _, err := os.Stat(filepath.Join(home, ".local", "state", "brain", "wrapper-backups")); err == nil {
		t.Error("dry run wrote a backup")
	}
}

// The plan's own drift wording is what the doctor reports, so the two verbs
// cannot disagree about what is wrong.
func TestWrapperPlanReportsDrift(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv(configfile.StoreHostFileEnvVar, writeScratchStoreHostRecord(t, home))
	beadsDir := filepath.Join(home, "data", "task", ".beads")
	if err := os.MkdirAll(beadsDir, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(beadsDir, "metadata.json"),
		[]byte(`{"dolt_mode":"server"}`), 0o600); err != nil {
		t.Fatal(err)
	}
	wdir := filepath.Join(home, ".local", "bin")
	if err := os.MkdirAll(wdir, 0o755); err != nil { //nolint:gosec // test dir
		t.Fatal(err)
	}
	wrapper := filepath.Join(wdir, "task")
	writeExec(t, wrapper, "#!/bin/sh\nexport BEADS_DIR=\"$HOME/data/task/.beads\"\nexport BEADS_DOLT_SERVER_HOST=127.0.0.1\nexport BEADS_DOLT_SERVER_PORT=3307\nexec bd \"$@\"\n")

	plan := wrapperPlanFor(wrapperTarget{
		name: "task", wrapper: wrapper, beadsDir: beadsDir, exists: true, serverMode: true,
		entry: storeEntry{Path: beadsDir},
	}, "bd")
	if !plan.BakedPin || !plan.changed || !plan.repointed {
		t.Errorf("plan = %+v", plan)
	}
	if len(plan.Drifts) == 0 || !strings.Contains(plan.Drifts[0], "pins BEADS_DOLT_SERVER_HOST/PORT") {
		t.Errorf("drift wording = %q", plan.Drifts)
	}

	// Once the planned body is in place, the wrapper is canonical: a second
	// plan reports no change and no drift.
	writeExec(t, wrapper, plan.body)
	canonical := wrapperPlanFor(wrapperTarget{
		name: "task", wrapper: wrapper, beadsDir: beadsDir, exists: true, serverMode: true,
		entry: storeEntry{Path: beadsDir},
	}, "bd")
	if canonical.changed || len(canonical.Drifts) != 0 {
		t.Errorf("canonical plan not clean: %+v", canonical)
	}
}
