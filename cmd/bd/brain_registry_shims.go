package main

// The local half of the store registry: turning a registry snapshot into the
// SHIMS a machine needs. The data of every store lives in the shared database;
// what a machine can lack is only the command that points at it (the wrapper
// in ~/.local/bin), its line in stores.yaml and stores.env, its BEADS_DIR
// skeleton (metadata.json), and the ~/.pi/agent/bin link. This file computes
// the difference between the desired shims and what is on disk (a plan) and
// applies it idempotently. It never deletes data and never touches a file it
// did not generate.

