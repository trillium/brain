// fakeStoreWrapper writes a wrapper that persists the probe table in a state dir.
func fakeStoreWrapper(t *testing.T, failInsert bool) (wrapper, state string) {
	t.Helper()
	dir := t.TempDir()
	state = filepath.Join(dir, "state")
	if err := os.MkdirAll(state, 0o755); err != nil {
		t.Fatal(err)
	}
	if failInsert {
		mustWrite(t, filepath.Join(state, "fail_insert"), "", 0o644)
	}
	wrapper = filepath.Join(dir, "fake")
	mustWrite(t, wrapper, `#!/bin/sh
S="`+state+`"
echo "$2" >> "$S/log"
case "$2" in
 CREATE*) touch "$S/table";;
 INSERT*) [ -f "$S/fail_insert" ] && { echo "Error: database is read only" >&2; exit 1; }; echo "$2" > "$S/row";;
 SELECT*) grep -o 'fleetprobe-[0-9-]*' "$S/row" 2>/dev/null;;
 DELETE*) rm -f "$S/row";;
 DROP*) rm -f "$S/table";;
esac
exit 0
`, 0o755)
	return wrapper, state
}

func exists(p string) bool { _, err := os.Stat(p); return err == nil }

func TestProbeStoreWriteLeavesNoFootprint(t *testing.T) {
	w, state := fakeStoreWrapper(t, false)
	r := probeStoreWrite(context.Background(), w, "fleetprobe-123-1")
	if r.Status != "ok" {
		t.Fatalf("probe = %+v", r)
	}
	if exists(filepath.Join(state, "table")) || exists(filepath.Join(state, "row")) {
		t.Fatal("the probe table or row survived a successful probe")
	}
	log, _ := os.ReadFile(filepath.Join(state, "log"))
	for _, l := range strings.Split(strings.TrimSpace(string(log)), "\n") {
		if strings.Contains(l, "issues") || strings.Contains(l, "dependencies") {
			t.Fatalf("probe touched bead data: %s", l)
		}
	}
}

