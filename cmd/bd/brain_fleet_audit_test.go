func idset(ids ...string) map[string]struct{} {
	m := map[string]struct{}{}
	for _, i := range ids {
		m[i] = struct{}{}
	}
	return m
}

func fakeScanner(servers map[string]map[string]map[string]struct{}) idScanner {
	return func(_ context.Context, a hostAddr) (map[string]map[string]struct{}, error) {
		if s, ok := servers[a.String()]; ok {
			return s, nil
		}
		return nil, errors.New("connection refused")
	}
}

