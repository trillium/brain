// ---- the audit half of the fleet view, end to end with a fake runner ----

type auditFake struct {
	mu       sync.Mutex
	audits   map[string]string // machine -> host-audit JSON ("" = unreachable)
	repaired []string
	calls    []string
}

func (f *auditFake) run(_ context.Context, m fleetMember, args ...string) ([]byte, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.calls = append(f.calls, m.Name+" "+strings.Join(args, " "))
	if f.audits[m.Name] == "" {
		return nil, errors.New("ssh: connect to host: Connection refused")
	}
	switch args[1] {
	case "host-audit":
		return []byte(f.audits[m.Name]), nil
	case "rewrite-wrappers":
		f.repaired = append(f.repaired, m.Name)
		f.audits[m.Name] = strings.ReplaceAll(f.audits[m.Name], `"host": "100.102.238.78"`, `"host": "100.84.99.99"`)
		return []byte(`{"total":1,"failed":0,"stores":[{"name":"task","status":"ok"}]}`), nil
	}
	return nil, fmt.Errorf("unexpected %v", args)
}

func auditJSON(storeHost string, pinHost string) string {
	sh := `{"path":"/h/store-host.env"}`
	if storeHost != "" {
		sh = fmt.Sprintf(`{"path":"/h/store-host.env","present":true,"host":%q,"port":3307}`, storeHost)
	}
	pins := `[]`
	if pinHost != "" {
		pins = fmt.Sprintf(`[{"name":"task","path":"/h/.local/bin/task","source":"wrapper","host": %q,"port":3307,"line":"export BEADS_DOLT_SERVER_HOST=x"}]`, pinHost)
	}
	return fmt.Sprintf(`{"machine":"x","bd_version":"1.3.1","stamp":{"commit":"aaaaaaaaaaaa","dirty":"no"},"store_host":%s,"pins":%s,"stores":[{"name":"task","read":{"status":"ok"},"write":{"status":"ok"},"backup":{"status":"ok","age_seconds":10}}]}`, sh, pins)
}

func TestRunFleetAuditReportsAndRepairsOnlyReachableWrapperPins(t *testing.T) {
	roster := []fleetMember{{Name: "mini0", SSH: "mini0"}, {Name: "mini1", SSH: "mini1"}, {Name: "mini2", SSH: "mini2"}, {Name: "macbook", SSH: "macbook"}}
	newFake := func() *auditFake {
		return &auditFake{audits: map[string]string{
			"mini0":   auditJSON("100.84.99.99", "100.102.238.78"), // wrapper pin overrides store-host.env
			"mini1":   auditJSON("", ""),                           // no store-host.env
			"mini2":   "",                                          // unreachable
			"macbook": auditJSON("100.84.99.99", ""),               // clean
		}}
	}
	opts := fleetAuditOptions{Live: liveMini0, LiveSource: "test", WriteProbe: true, BackupMax: 48 * time.Hour, MainSHA: "aaaaaaaaaaaa",
		LiveChecker: func(context.Context, hostAddr) error { return nil }}

	// Report-only (the default): drift is found and nothing is repaired.
	f := newFake()
	rep := runFleetAudit(context.Background(), roster, f.run, opts, time.Second)
	if rep.Clean {
		t.Fatal("a drifted fleet must not be clean")
	}
	got := map[string]string{}
	for _, d := range rep.Drift {
		got[d.Machine] += d.Kind + " "
	}
	if got["mini0"] != "pin " || got["mini1"] != "store-host " || got["mini2"] != "unreachable " || got["macbook"] != "" {
		t.Errorf("drift by machine = %v", got)
	}
	if len(f.repaired) != 0 {
		t.Fatalf("report-only run repaired %v", f.repaired)
	}
	for _, c := range f.calls {
		if strings.Contains(c, "--write-probe") == false && strings.Contains(c, "host-audit") {
			t.Errorf("write probe flag missing from %q", c)
		}
	}

	// --repair: only mini0 (reachable, wrapper pin, store-host.env present).
	f = newFake()
	opts.Repair = true
	rep = runFleetAudit(context.Background(), roster, f.run, opts, time.Second)
	if strings.Join(f.repaired, ",") != "mini0" {
		t.Fatalf("repaired = %v, want only mini0", f.repaired)
	}
	got = map[string]string{}
	for _, d := range rep.Drift {
		got[d.Machine] += d.Kind + " "
	}
	if got["mini0"] != "" || got["mini1"] != "store-host " || got["mini2"] != "unreachable " {
		t.Errorf("after repair drift = %v", got)
	}
	for _, c := range f.calls {
		if strings.HasPrefix(c, "mini2 stores rewrite") || strings.HasPrefix(c, "mini1 stores rewrite") {
			t.Errorf("repair touched a host it must not: %q", c)
		}
	}
}

