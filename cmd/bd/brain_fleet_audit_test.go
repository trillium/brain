const generatedHostBlockWrapper = "#!/bin/sh\n# Auto-generated by 'brain stores create x'.\n" + "{BLOCK}" + "export BEADS_DIR=$HOME/x/.beads\nexec bd \"$@\"\n"

func TestCollectHostPinsFindsWrapperAndShimEnvPins(t *testing.T) {
	home := t.TempDir()
	// A canonical generated wrapper carries the run-time block, not a pin.
	mustWrite(t, filepath.Join(home, ".local/bin/clean"), strings.Replace(generatedHostBlockWrapper, "{BLOCK}", sharedServerHostBlock, 1), 0o755)
	// A wrapper with a baked pin (the 'task on mini0 reached mini1' case).
	mustWrite(t, filepath.Join(home, ".local/bin/task"), "#!/bin/sh\nexport BEADS_DOLT_SERVER_HOST=100.102.238.78\nexport BEADS_DOLT_SERVER_PORT=3307\nexec bd \"$@\"\n", 0o755)
	// A wrapper that sources a retired shim env file.
	mustWrite(t, filepath.Join(home, ".local/bin/viaenv"), "#!/bin/sh\n. \"$HOME/.config/brain-remote/mini1.env\"\nexec bd \"$@\"\n", 0o755)
	mustWrite(t, filepath.Join(home, ".config/brain-remote/mini1.env"), "BEADS_DOLT_SERVER_HOST=100.102.238.78\n", 0o644)
	// A shim env file nobody sources still counts.
	mustWrite(t, filepath.Join(home, ".config/brain-remote/lonely.env"), "export BEADS_DOLT_SERVER_PORT=3399\n", 0o644)
	// Backups and non-scripts are ignored.
	mustWrite(t, filepath.Join(home, ".local/bin/task.bak-repoint-1"), "#!/bin/sh\nexport BEADS_DOLT_SERVER_HOST=9.9.9.9\n", 0o644)
	mustWrite(t, filepath.Join(home, ".local/bin/blob"), "\x7fELF BEADS_DOLT_SERVER_HOST=1.1.1.1", 0o755)
	// A comment is not a pin.
	mustWrite(t, filepath.Join(home, ".local/bin/doc"), "#!/bin/sh\n# BEADS_DOLT_SERVER_HOST=2.2.2.2 would override\nexec bd \"$@\"\n", 0o755)

	pins, wrappers := collectHostPins(home)
	if wrappers != 4 {
		t.Errorf("wrappers = %d, want 4 (clean, task, viaenv, doc)", wrappers)
	}
	got := map[string]string{}
	for _, p := range pins {
		got[p.Name+"/"+p.Source] += pinAddr(p) + ";"
	}
	want := map[string]string{
		"task/wrapper":        "100.102.238.78;?:3307;",
		"mini1.env/env-file":  "100.102.238.78;",
		"lonely.env/env-file": "?:3399;",
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("pin %s = %q, want %q (all: %v)", k, got[k], v, got)
		}
	}
	if len(got) != len(want) {
		t.Errorf("unexpected pins: %v", got)
	}
	for _, p := range pins {
		if p.Name == "mini1.env" && p.Via != "viaenv" && p.Via != "" {
			t.Errorf("env pin via = %q", p.Via)
		}
	}
}

