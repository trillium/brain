// registryWriteTarget answers whether the registry is adopted in the
// database the caller is connected to. When it is not, lifecycle verbs keep
// their local-only behaviour (and say so).
func registryWriteTarget(ctx context.Context) (db *sql.DB, adopted bool) {
	if strings.EqualFold(os.Getenv(envRegistryOff), "off") || storesLocalOnly {
		return nil, false
	}
	d, err := registryDBFunc()
	if err != nil || d == nil {
		return nil, false
	}
	if _, found, err := storeregistry.ReadState(ctx, d); err != nil || !found {
		return nil, false
	}
	return d, true
}

func registryMeta() storeregistry.Meta {
	actor := os.Getenv("BD_ACTOR")
	if actor == "" {
		actor = "brain"
	}
	return storeregistry.Meta{Actor: actor, Machine: machineName()}
}

// homeRelativeDir returns dir relative to $HOME, and whether it lies under it.
func homeRelativeDir(dir string) (string, bool) {
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return "", false
	}
	rel, err := filepath.Rel(home, dir)
	if err != nil || strings.HasPrefix(rel, "..") {
		return "", false
	}
	return filepath.ToSlash(rel), true
}

// syncThisMachine applies the registry to this machine right after a
// lifecycle change, and returns the "epoch N; k of n converged" line.
func syncThisMachine(ctx context.Context, db *sql.DB, epoch int64) string {
	rep, err := runRegistrySync(ctx, syncOptions{Source: dbSource{db: db}, Force: true, Wait: 30 * time.Second, Trigger: "lifecycle"})
	line := fleetConvergenceLine(ctx, db, epoch)
	if err != nil {
		return fmt.Sprintf("%s (local sync failed: %s; run 'brain stores sync')", line, firstErrLine(err))
	}
	if rep.Status == "partial" {
		return fmt.Sprintf("%s (local sync incomplete: run 'brain stores sync')", line)
	}
	return line
}

// fleetConvergenceLine is "epoch N; k of n machines converged", from the
// machines' own reports. It never waits for the fleet.
func fleetConvergenceLine(ctx context.Context, db storeregistry.DBTX, epoch int64) string {
	ms, err := storeregistry.ReadMachines(ctx, db)
	if err != nil {
		return fmt.Sprintf("epoch %d", epoch)
	}
	n, k := 0, 0
	for _, m := range ms {
		if m.Retired {
			continue
		}
		n++
		if m.AppliedEpoch >= epoch {
			k++
		}
	}
	if n == 0 {
		return fmt.Sprintf("epoch %d; no machine has reported yet", epoch)
	}
	line := fmt.Sprintf("epoch %d; %d of %d machines converged", epoch, k, n)
	if k < n {
		line += " (the rest converge on their next command or within 5 minutes; 'brain stores doctor --fleet' is the proof)"
	}
	return line
}

