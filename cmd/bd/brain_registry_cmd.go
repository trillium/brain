// registrySourceForCommand picks where this command reads the registry from:
// the relay host on a client machine, the shared database otherwise.
func registrySourceForCommand() (registrySource, error) {
	if src, ok := clientSourceIfConfigured(); ok {
		return src, nil
	}
	db, err := registryDBFunc()
	if err != nil {
		return nil, err
	}
	return dbSource{db: db}, nil
}

var brainStoresSyncCmd = &cobra.Command{
	Use:   "sync",
	Short: "Make this machine's store shims match the shared registry (idempotent)",
	Long: `Reconcile this machine with the fleet's store registry.

The data of every store lives in the one shared database; so does the list of
stores (names, prefixes) and a version counter, the epoch, that goes up in the
same transaction as every create, rename or remove. What a machine can lack is
only the local shim that points at that data: the wrapper command in
~/.local/bin, its line in stores.yaml / stores.env, its BEADS_DIR skeleton, and
its ~/.pi/agent/bin link. 'sync' computes the difference and applies it.

  - It reads state, not events: a machine that slept through ten changes
    converges in one run.
  - It is idempotent: a second run changes nothing.
  - It never deletes data and never touches a file brain did not generate (a
    wrapper without the 'Auto-generated by brain stores' marker is reported,
    not rewritten or removed). Replaced or removed files are backed up under
    ~/.local/share/brain/registry-backup/<time>/ with a restore.sh.
  - A removed store leaves a tombstone; each machine removes only its own
    generated wrapper and link. Database rows and data directories stay.

Triggers: the launchd poller (every 5 minutes and at load), the ride-along on
every bd/brain command, and create/rename/remove on the machine that made the
change. --dry-run prints the plan and changes nothing.

--machine NAME runs the sync on that fleet machine over ssh (see
'brain stores doctor --fleet' for the roster).

Exit codes: 0 converged (or nothing adopted yet), 1 partial (items listed),
3 the registry could not be read.`,
	Args: cobra.NoArgs,
	Run:  runBrainStoresSync,
}

func runBrainStoresSync(cmd *cobra.Command, _ []string) {
	if syncMachine != "" && syncMachine != machineName() {
		os.Exit(runFleetMachineSync(cmd.Context(), syncMachine, syncDryRun))
	}
	ctx := rootCtx
	if ctx == nil {
		ctx = context.Background()
	}
	src, err := registrySourceForCommand()
	if err != nil {
		if syncQuiet {
			os.Exit(0) // the timer: an unreachable database is not an error to page anyone about
		}
		fmt.Fprintf(os.Stderr, "brain stores sync: cannot reach the registry: %v\n", err)
		os.Exit(3)
	}
	rep, err := runRegistrySync(ctx, syncOptions{Source: src, DryRun: syncDryRun, Force: syncForce, Wait: syncWait, Trigger: syncTrigger})
	if err != nil {
		if syncQuiet {
			fmt.Fprintf(os.Stderr, "%s brain stores sync: %v\n", time.Now().UTC().Format(time.RFC3339), err)
			os.Exit(0)
		}
		fmt.Fprintf(os.Stderr, "brain stores sync: %v\n", err)
		os.Exit(3)
	}
	if jsonOutput {
		_ = outputJSON(rep)
	} else if !syncQuiet || rep.Changed > 0 || rep.Status == "partial" {
		printSyncReport(os.Stdout, rep, syncDryRun)
	}
	if rep.Status == "partial" {
		os.Exit(1)
	}
}

