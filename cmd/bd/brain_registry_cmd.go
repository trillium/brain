// verifyReport is what one machine says about itself, computed from its actual
// files (not only from its own state file). 'doctor --fleet' collects these.
type verifyReport struct {
	Machine       string              `json:"machine"`
	Role          string              `json:"role"`
	Relay         string              `json:"relay,omitempty"`
	AppliedEpoch  int64               `json:"applied_epoch"`
	AppliedDigest string              `json:"applied_digest"`
	RegistryEpoch int64               `json:"registry_epoch"`
	RegistryHash  string              `json:"registry_digest"`
	Source        string              `json:"source"` // database | relay | cache
	Active        int                 `json:"active"`
	WrappersOK    int                 `json:"wrappers_ok"`
	Missing       map[string][]string `json:"missing"`
	Orphans       []string            `json:"orphans"`
	LocalOnly     []string            `json:"local_only"`
	Probes        []storeHealth       `json:"probes,omitempty"`
	BdVersion     string              `json:"bd_version"`
	PollerLoaded  bool                `json:"poller_installed"`
	Error         string              `json:"error,omitempty"`
}

// Converged reports whether the machine matches the registry it read.
func (v verifyReport) Converged() bool {
	if v.Error != "" || v.AppliedEpoch != v.RegistryEpoch || v.AppliedDigest != v.RegistryHash {
		return false
	}
	for _, m := range v.Missing {
		if len(m) > 0 {
			return false
		}
	}
	for _, p := range v.Probes {
		if p.Status == "fail" {
			return false
		}
	}
	return true
}

// buildVerifyReport inspects this machine read-only.
func buildVerifyReport(ctx context.Context, src registrySource, probes int) verifyReport {
	machine := machineName()
	role, relay := src.Role()
	applied, _ := readAppliedState()
	v := verifyReport{Machine: machine, Role: role, Relay: relay, BdVersion: Version,
		AppliedEpoch: applied.Epoch, AppliedDigest: applied.Digest, Source: "database",
		Missing: map[string][]string{}, PollerLoaded: pollerInstalled()}
	if role == "client" {
		v.Source = "relay"
	}
	snap, found, err := src.Snapshot(ctx)
	if err != nil {
		// Offline: fall back to the last snapshot this machine saw.
		c, ok := readRegistryCache()
		if !ok {
			v.Error = "registry unreadable: " + firstErrLine(err)
			return v
		}
		snap = storeregistry.Snapshot{State: storeregistry.State{Epoch: c.Epoch, Digest: c.Digest}, Entries: c.Entries}
		v.Source = "cache"
		v.Error = ""
	} else if !found {
		v.Error = "registry not adopted in this database"
		return v
	}
	v.RegistryEpoch, v.RegistryHash = snap.State.Epoch, snap.State.Digest
	env := newShimEnv(ctx, src, machine)
	plan, err := buildSyncPlan(env, snap)
	if err != nil {
		v.Error = err.Error()
		return v
	}
	v.Active, v.WrappersOK = plan.Active, plan.WrappersOK
	for k, names := range plan.Missing {
		if len(names) > 0 {
			sort.Strings(names)
			v.Missing[k] = names
		}
	}
	v.Orphans, v.LocalOnly = plan.Orphans, plan.LocalOnly
	if probes > 0 && role == "direct" {
		v.Probes = probeNewestStores(snap.Entries, probes)
	}
	return v
}

// probeNewestStores reads through the wrappers of the newest N stores: the
// functional proof that "the command exists" also means "the command works".
func probeNewestStores(entries []storeregistry.Entry, n int) []storeHealth {
	act := storeregistry.Active(entries)
	sort.Slice(act, func(i, j int) bool { return act[i].ChangedEpoch > act[j].ChangedEpoch })
	self, _ := os.Executable()
	home, _ := os.UserHomeDir()
	var out []storeHealth
	for _, e := range act {
		if len(out) >= n {
			break
		}
		if e.Kind != storeregistry.KindStore {
			continue
		}
		out = append(out, probeStore(self, e.Name, storeEntry{Path: filepath.Join(home, e.RelPath)}, 15*time.Second))
	}
	return out
}

var brainStoresVerifyCmd = &cobra.Command{
	Use:   "verify",
	Short: "Report this machine's registry state from its actual files (read-only)",
	Long: `Compare this machine's real wrappers, agent links, stores.yaml and stores.env
with the registry and print what is missing or orphaned. Changes nothing.
'brain stores doctor --fleet' runs this over ssh on every machine in the roster.`,
	Args: cobra.NoArgs,
	Run: func(cmd *cobra.Command, _ []string) {
		src, err := registrySourceForCommand()
		if err != nil {
			v := verifyReport{Machine: machineName(), Error: "cannot reach the registry: " + firstErrLine(err), BdVersion: Version}
			if c, ok := readRegistryCache(); ok {
				v.RegistryEpoch, v.RegistryHash = c.Epoch, c.Digest
			}
			emitVerify(v)
			os.Exit(3)
		}
		ctx := rootCtx
		if ctx == nil {
			ctx = context.Background()
		}
		v := buildVerifyReport(ctx, src, verifyProbe)
		emitVerify(v)
		if !v.Converged() {
			os.Exit(1)
		}
	},
}

func emitVerify(v verifyReport) {
	if jsonOutput {
		_ = outputJSON(v)
		return
	}
	fmt.Printf("machine %s (%s): applied epoch %d, registry epoch %d [%s]\n", v.Machine, v.Role, v.AppliedEpoch, v.RegistryEpoch, v.Source)
	fmt.Printf("  %d/%d active names have a working wrapper\n", v.WrappersOK, v.Active)
	kinds := make([]string, 0, len(v.Missing))
	for k := range v.Missing {
		kinds = append(kinds, k)
	}
	sort.Strings(kinds)
	for _, k := range kinds {
		fmt.Printf("  missing %s: %s\n", k, strings.Join(v.Missing[k], " "))
	}
	for _, o := range v.Orphans {
		fmt.Printf("  orphan (removed in the registry, wrapper not generated by brain): %s\n", o)
	}
	for _, l := range v.LocalOnly {
		fmt.Printf("  local-only (not in the registry): %s\n", l)
	}
	if v.Error != "" {
		fmt.Printf("  error: %s\n", v.Error)
	}
	if v.Converged() {
		fmt.Println("converged")
	}
}

