// registryLocalVerb reports whether args name a registry verb that acts on
// this machine's own files and so must not be forwarded to the brain host.
func registryLocalVerb(args []string) bool {
	var words []string
	fleet := false
	for _, a := range args {
		if a == "--fleet" {
			fleet = true
		}
		if strings.HasPrefix(a, "-") {
			continue
		}
		words = append(words, a)
	}
	if len(words) > 0 && words[0] == "brain" {
		words = words[1:]
	}
	if len(words) < 2 || words[0] != "stores" {
		return false
	}
	switch words[1] {
	case "sync", "verify", "poller", "shell-hook":
		return true
	case "doctor":
		return fleet
	}
	return false
}
