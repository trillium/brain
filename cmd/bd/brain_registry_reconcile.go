package main

// 'brain stores reconcile': the one-time recovery that merges an out-of-sync
// brain into one. It adopts what is certain (every store this machine already
// registers in stores.yaml, with its alias wrappers) and ASKS about what is
// not: names the database knows that no registry lists. It never guesses; it
// writes a report and a decisions file for a human to fill in.

import (
	"bytes"
	"context"
	"database/sql"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"gopkg.in/yaml.v3"

	"github.com/steveyegge/beads/internal/storeregistry"
)

const (
	reconcileReportPath    = ".config/brain/reconcile-report.md"
	reconcileDecisionsPath = ".config/brain/reconcile-decisions.yaml"
)

var (
	reconcileApply     bool
	reconcileReport    string
	reconcileDecisions string
)

var wrapperBDNameRe = regexp.MustCompile(`\bBD_NAME="?([A-Za-z0-9:_-]+)"?`)

// dbOnlyStore is a name the database knows that no registry or stores.yaml lists.
type dbOnlyStore struct {
	Key         string   `json:"key"` // the brain_stores / prefix-owner name
	Registered  bool     `json:"registered"`
	SourceDB    string   `json:"source_database"`
	BeadsDir    string   `json:"beads_dir"`
	Prefixes    []string `json:"prefixes"`
	BeadCount   int64    `json:"bead_count"`
	HasWrapper  bool     `json:"has_wrapper_here"`
	HasDataDir  bool     `json:"has_data_dir_here"`
	SuggestName string   `json:"suggested_command_name"`
}

// reconcileDecision is one line of the decisions file.
type reconcileDecision struct {
	Action string `yaml:"action"` // store | not-a-store | "" (undecided)
	Name   string `yaml:"name,omitempty"`
	Note   string `yaml:"note,omitempty"`
}

type reconcileDecisionFile struct {
	Decisions map[string]reconcileDecision `yaml:"decisions"`
}

type reconcilePlan struct {
	Adopt     []storeregistry.Entry // certain: registered locally, valid
	Aliases   []storeregistry.Entry
	Refused   []string // yaml stores that cannot be adopted, with the reason
	DBOnly    []dbOnlyStore
	Decided   []storeregistry.Entry // db-only names the human said are stores
	NotStores []string
	Undecided []string
	AliasRows map[string]string // alias -> store key to ensure in brain_store_aliases
}

func suggestCommandName(key string) string {
	n := strings.ToLower(strings.TrimPrefix(key, "db:"))
	n = strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_' || r == '-' {
			return r
		}
		return '_'
	}, n)
	if !storeregistry.ValidName(n) {
		return ""
	}
	return n
}

func detectWrapperKindFor(name, absDir string) string {
	if wp, ok := storeWrapperPath(name); ok {
		if data, err := os.ReadFile(wp); err == nil {
			if bytes.Contains(data, []byte("BEADS_DOLT_SERVER_MODE")) || bytes.Contains(data, []byte("store-host.env")) {
				return storeregistry.WrapperServer
			}
		}
	}
	if st, err := os.Stat(filepath.Join(absDir, ".dolt")); err == nil && st.IsDir() {
		return storeregistry.WrapperEmbedded
	}
	return storeregistry.WrapperServer
}

// planReconcile gathers the facts. It reads and decides nothing destructive.
func planReconcile(ctx context.Context, db *sql.DB, snap storeregistry.Snapshot, adopted bool, decisions reconcileDecisionFile) (*reconcilePlan, error) {
	home, _ := os.UserHomeDir()
	yamlStores, err := loadStoresRegistry()
	if err != nil {
		return nil, err
	}
	inRegistry := map[string]bool{}
	storeKeys := map[string]bool{}
	for _, e := range snap.Entries {
		inRegistry[e.Name] = true
		storeKeys[e.Store] = true
	}
	p := &reconcilePlan{AliasRows: map[string]string{}}

	for _, name := range sortedKeys(yamlStores) {
		if inRegistry[name] {
			continue
		}
		ent := yamlStores[name]
		rel, ok := homeRelativeDir(ent.Path)
		e := storeregistry.Entry{Name: name, Kind: storeregistry.KindStore, Store: name, State: storeregistry.StateActive,
			RelPath: rel, WrapperKind: detectWrapperKindFor(name, filepath.Dir(ent.Path)), About: ent.About, EditBack: ent.EditBack}
		switch {
		case !ok:
			p.Refused = append(p.Refused, fmt.Sprintf("%s: path %s is not under $HOME (a registry path is HOME-relative)", name, ent.Path))
		case e.Validate() != nil:
			p.Refused = append(p.Refused, fmt.Sprintf("%s: %v", name, e.Validate()))
		default:
			p.Adopt = append(p.Adopt, e)
		}
	}

	// Alias wrappers generated by 'brain stores alias' (found by their header).
	adoptable := map[string]storeregistry.Entry{}
	for _, e := range p.Adopt {
		adoptable[e.Name] = e
	}
	for _, e := range snap.Entries {
		adoptable[e.Name] = e
	}
	for _, t := range collectWrapperTargets(yamlStores) {
		if _, isStore := yamlStores[t.name]; isStore || inRegistry[t.name] {
			continue
		}
		wp, _ := storeWrapperPath(t.name)
		data, err := os.ReadFile(wp)
		if err != nil {
			continue
		}
		m := wrapperBDNameRe.FindSubmatch(data)
		if m == nil {
			continue
		}
		canon := string(m[1])
		target, ok := adoptable[canon]
		if !ok || target.State != storeregistry.StateActive {
			p.Refused = append(p.Refused, fmt.Sprintf("%s: alias of %q, which is not an adoptable store", t.name, canon))
			continue
		}
		a := storeregistry.Entry{Name: t.name, Kind: storeregistry.KindAlias, Store: target.Store, State: storeregistry.StateActive,
			RelPath: target.RelPath, WrapperKind: target.WrapperKind}
		if a.Validate() != nil {
			p.Refused = append(p.Refused, fmt.Sprintf("%s: %v", t.name, a.Validate()))
			continue
		}
		p.Aliases = append(p.Aliases, a)
	}

	// What the database knows that nothing lists.
	only := map[string]*dbOnlyStore{}
	get := func(k string) *dbOnlyStore {
		if only[k] == nil {
			only[k] = &dbOnlyStore{Key: k}
		}
		return only[k]
	}
	if rows, err := db.QueryContext(ctx, "SELECT `store`, registered, source_database, beads_dir FROM brain_stores"); err == nil {
		for rows.Next() {
			var s, src, bd string
			var reg int
			if rows.Scan(&s, &reg, &src, &bd) == nil && !inRegistry[s] && !storeKeys[s] {
				if _, yamlHas := yamlStores[s]; !yamlHas {
					o := get(s)
					o.Registered, o.SourceDB, o.BeadsDir = reg == 1, src, bd
				}
			}
		}
		_ = rows.Close()
	}
	if rows, err := db.QueryContext(ctx, "SELECT prefix, `store`, bead_count FROM brain_store_prefixes"); err == nil {
		for rows.Next() {
			var pre, s string
			var n int64
			if rows.Scan(&pre, &s, &n) == nil && !inRegistry[s] && !storeKeys[s] {
				if _, yamlHas := yamlStores[s]; !yamlHas {
					o := get(s)
					o.Prefixes = append(o.Prefixes, pre)
					o.BeadCount += n
				}
			}
		}
		_ = rows.Close()
	}
	keys := make([]string, 0, len(only))
	for k := range only {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		o := only[k]
		o.SuggestName = suggestCommandName(k)
		if o.SuggestName != "" {
			_, o.HasWrapper = storeWrapperPath(o.SuggestName)
			if st, err := os.Stat(filepath.Join(home, "data", o.SuggestName)); err == nil && st.IsDir() {
				o.HasDataDir = true
			}
		}
		sort.Strings(o.Prefixes)
		p.DBOnly = append(p.DBOnly, *o)
		d := decisions.Decisions[k]
		switch d.Action {
		case "store":
			name := d.Name
			if name == "" {
				name = o.SuggestName
			}
			e := storeregistry.Entry{Name: name, Kind: storeregistry.KindStore, Store: k, State: storeregistry.StateActive,
				RelPath: "data/" + name + "/.beads", WrapperKind: storeregistry.WrapperServer}
			if err := e.Validate(); err != nil {
				p.Refused = append(p.Refused, fmt.Sprintf("%s: decided 'store' but %v", k, err))
				p.Undecided = append(p.Undecided, k)
				continue
			}
			p.Decided = append(p.Decided, e)
			if name != k {
				p.AliasRows[name] = k
			}
		case "not-a-store":
			p.NotStores = append(p.NotStores, k)
		default:
			p.Undecided = append(p.Undecided, k)
		}
	}
	return p, nil
}

func loadReconcileDecisions(path string) reconcileDecisionFile {
	d := reconcileDecisionFile{Decisions: map[string]reconcileDecision{}}
	if data, err := os.ReadFile(path); err == nil {
		_ = yaml.Unmarshal(data, &d)
		if d.Decisions == nil {
			d.Decisions = map[string]reconcileDecision{}
		}
	}
	return d
}

// writeReconcileFiles writes the human-readable report and, without
// overwriting any decision already made, the decisions template.
func writeReconcileFiles(reportPath, decisionsPath string, p *reconcilePlan, epoch int64, adopted bool) error {
	var b strings.Builder
	b.WriteString("# Store registry reconcile report\n\n")
	fmt.Fprintf(&b, "Registry adopted: %v (epoch %d). This machine: %s.\n\n", adopted, epoch, machineName())
	fmt.Fprintf(&b, "## Certain: %d store(s) and %d alias(es) this machine already registers\n\n", len(p.Adopt), len(p.Aliases))
	b.WriteString("`brain stores reconcile --apply` writes these into the shared registry.\n\n")
	for _, e := range p.Adopt {
		fmt.Fprintf(&b, "- `%s` → `%s` (%s wrapper)\n", e.Name, e.RelPath, e.WrapperKind)
	}
	for _, e := range p.Aliases {
		fmt.Fprintf(&b, "- alias `%s` → `%s`\n", e.Name, e.Store)
	}
	if len(p.Refused) > 0 {
		b.WriteString("\n## Cannot be adopted (fix by hand)\n\n")
		for _, r := range p.Refused {
			fmt.Fprintf(&b, "- %s\n", r)
		}
	}
	fmt.Fprintf(&b, "\n## Needs a human: %d name(s) the database knows that no registry lists\n\n", len(p.DBOnly))
	b.WriteString("Nothing here is guessed. For each, edit `" + decisionsPath + "`: set `action: store` (and `name:` if the\n")
	b.WriteString("suggested command name is wrong) or `action: not-a-store`. Then run `brain stores reconcile --apply`.\n\n")
	for _, o := range p.DBOnly {
		fmt.Fprintf(&b, "### `%s`\n\n- registered in brain_stores: %v; source database: %q; beads dir: %q\n- prefixes: %s; beads under them: %d\n- suggested command name: `%s`; wrapper already here: %v; ~/data/%s exists here: %v\n\n",
			o.Key, o.Registered, o.SourceDB, o.BeadsDir, strings.Join(o.Prefixes, ", "), o.BeadCount, o.SuggestName, o.HasWrapper, o.SuggestName, o.HasDataDir)
	}
	if err := writeFileAtomic(reportPath, []byte(b.String()), 0o644); err != nil {
		return err
	}
	dec := loadReconcileDecisions(decisionsPath)
	for _, o := range p.DBOnly {
		if _, ok := dec.Decisions[o.Key]; !ok {
			dec.Decisions[o.Key] = reconcileDecision{Action: "", Name: o.SuggestName,
				Note: fmt.Sprintf("registered=%v beads=%d prefixes=%s", o.Registered, o.BeadCount, strings.Join(o.Prefixes, ","))}
		}
	}
	out, err := yaml.Marshal(dec)
	if err != nil {
		return err
	}
	header := "# Fill in `action:` for each name: store | not-a-store. Empty means undecided; reconcile never guesses.\n"
	return writeFileAtomic(decisionsPath, append([]byte(header), out...), 0o644)
}

var brainStoresReconcileCmd = &cobra.Command{
	Use:   "reconcile",
	Short: "One-time recovery: adopt this machine's stores into the shared registry and report what needs a human",
	Long: `Merge an out-of-sync brain back into one.

Without --apply it only reads: it compares this machine's stores.yaml and alias
wrappers and the database's namespace record with the shared registry, and
writes
  ~/.config/brain/reconcile-report.md        what is certain and what is not
  ~/.config/brain/reconcile-decisions.yaml   one line per name the database knows
                                             that no registry lists (undecided)

With --apply it adopts the certain stores and aliases into the registry (one
transaction, one epoch), applies every name you decided 'store' in the
decisions file, and then syncs this machine. Names left undecided stay
undecided; 'not-a-store' names are never registered. Run it on one machine
(the one whose stores.yaml is the truth), then 'brain stores sync' (or just
wait) everywhere else.`,
	Args: cobra.NoArgs,
	Run: func(cmd *cobra.Command, _ []string) {
		ctx := rootCtx
		db, err := registryDBFunc()
		if err != nil {
			FatalError("cannot reach the shared database: %v", err)
		}
		snap, adopted, err := storeregistry.ReadSnapshot(ctx, db)
		if err != nil {
			FatalError("%v", err)
		}
		reportPath, decisionsPath := reconcileReport, reconcileDecisions
		if reportPath == "" {
			reportPath = homeFile(reconcileReportPath)
		}
		if decisionsPath == "" {
			decisionsPath = homeFile(reconcileDecisionsPath)
		}
		plan, err := planReconcile(ctx, db, snap, adopted, loadReconcileDecisions(decisionsPath))
		if err != nil {
			FatalError("%v", err)
		}
		if !reconcileApply {
			if err := writeReconcileFiles(reportPath, decisionsPath, plan, snap.State.Epoch, adopted); err != nil {
				FatalError("writing the report: %v", err)
			}
			fmt.Printf("%d store(s) and %d alias(es) are certain; %d name(s) need a decision.\nreport:    %s\ndecisions: %s\nNothing was changed. Review, then: brain stores reconcile --apply\n",
				len(plan.Adopt), len(plan.Aliases), len(plan.DBOnly), reportPath, decisionsPath)
			return
		}

		res, err := applyReconcile(ctx, db, plan)
		if err != nil {
			FatalError("%v", err)
		}
		_ = writeReconcileFiles(reportPath, decisionsPath, plan, res.Epoch, true)
		line := syncThisMachine(ctx, db, res.Epoch)
		fmt.Printf("adopted %d store(s)/alias(es): %s\n", len(res.Changes), line)
		if len(plan.Undecided) > 0 {
			fmt.Printf("%d name(s) still undecided (see %s): %s\n", len(plan.Undecided), decisionsPath, strings.Join(plan.Undecided, " "))
		}
		for _, r := range plan.Refused {
			fmt.Printf("not adopted: %s\n", r)
		}
	},
}

// applyReconcile adopts the registry (idempotent) and writes the certain and
// the decided entries in one transaction, plus the database aliases a decided
// name needs.
func applyReconcile(ctx context.Context, db *sql.DB, plan *reconcilePlan) (storeregistry.Result, error) {
	meta := registryMeta()
	if _, err := storeregistry.Init(ctx, db, meta); err != nil {
		return storeregistry.Result{}, fmt.Errorf("adopting the registry: %w", err)
	}
	all := append(append(append([]storeregistry.Entry{}, plan.Adopt...), plan.Aliases...), plan.Decided...)
	if len(plan.AliasRows) > 0 {
		rows := plan.AliasRows
		meta.InTx = func(ctx context.Context, tx storeregistry.DBTX) error {
			for alias, store := range rows {
				if _, err := tx.ExecContext(ctx, "REPLACE INTO brain_store_aliases (alias, `store`) VALUES (?, ?)", alias, store); err != nil {
					return fmt.Errorf("recording alias %s → %s: %w", alias, store, err)
				}
			}
			return nil
		}
	}
	res, err := storeregistry.Mutate(ctx, db, meta, storeregistry.PlanBackfill(all))
	if err != nil {
		return res, fmt.Errorf("writing the registry: %w", err)
	}
	if !res.Changed {
		st, _, _ := storeregistry.ReadState(ctx, db)
		res.Epoch = st.Epoch
	}
	return res, nil
}

func init() {
	brainStoresReconcileCmd.Flags().BoolVar(&reconcileApply, "apply", false, "Write the adoption into the shared registry (default: report only)")
	brainStoresReconcileCmd.Flags().StringVar(&reconcileReport, "report", "", "Report file (default ~/.config/brain/reconcile-report.md)")
	brainStoresReconcileCmd.Flags().StringVar(&reconcileDecisions, "decisions", "", "Decisions file (default ~/.config/brain/reconcile-decisions.yaml)")
	brainStoresCmd.AddCommand(brainStoresReconcileCmd)
}
