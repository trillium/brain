// wrapperRewrite is the outcome for one wrapper: its home path was made
// $HOME-relative and/or its Dolt host was repointed at the shared store host
// config, and it was then read through (the same probe 'brain stores doctor'
// uses).
type wrapperRewrite struct {
	Name    string `json:"name"`
	Wrapper string `json:"wrapper,omitempty"`
	Status  string `json:"status"` // "ok" | "fail"
	Reason  string `json:"reason,omitempty"`
	// Repointed is true when the wrapper was rewritten to resolve its Dolt
	// host from the shared store host config at run time (a baked host pin was
	// dropped or the runtime block was added).
	Repointed bool `json:"repointed,omitempty"`
	// Generated is true when the store had no wrapper at all and this run wrote
	// the canonical one.
	Generated bool `json:"generated,omitempty"`
	// Changed is true when the wrapper's content differs from what it was (or,
	// under --dry-run, would differ).
	Changed bool `json:"changed,omitempty"`
	// Backup names the file the previous wrapper was preserved in, when it was
	// rewritten. Empty when nothing changed or no backup was taken.
	Backup string `json:"backup,omitempty"`
	// WouldWrite is true under --dry-run when the run would have changed the
	// wrapper; DryRun is true on every result of a dry run.
	WouldWrite bool `json:"would_write,omitempty"`
	DryRun     bool `json:"dry_run,omitempty"`
}

const aliasWrapperHeader = "# Auto-generated by 'brain stores alias "

var (
	wrapperHomeVarRe = regexp.MustCompile(`\b(BEADS_DIR|BRAIN_KNOWLEDGE_ROOT)=(?:"([^"]*)"|([^\s"]+))`)
	foreignHomeRe    = regexp.MustCompile(`^/(?:Users|home)/[^/]+(/.*)?$`)
	wrapperBeadsRe   = regexp.MustCompile(`\bBEADS_DIR="?([^"\s]+)"?`)
	pathEscaper      = strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "`", "\\`")
	// bakedServerPinLineRe matches an 'export BEADS_DOLT_SERVER_HOST/PORT=' line
	// — the pin older generated wrappers baked in. Such a pin wins over the
	// shared store host record, so a leftover one is exactly how a host drifts
	// to a stale local daemon. A canonical wrapper's OWN exports are written
	// from the record's values ($_want_host/$_want_port) and are deliberately
	// NOT pins: stripping them would leave the child with no resolved host at
	// all. stripBakedServerPins is the only thing that removes lines, so this
	// distinction lives in one place.
	bakedServerPinLineRe = regexp.MustCompile(`^export BEADS_DOLT_SERVER_(?:HOST|PORT)=`)
	// resolvedHostValueRe matches a value written from the record's own
	// variables, as sharedServerHostBlock does.
	resolvedHostValueRe = regexp.MustCompile(`_want_(?:host|port)|_store_host_file`)
)

// stripBakedServerPins removes the literal host/port pins an older wrapper
// baked in, and nothing else. A line whose value comes from the shared record
// ($_want_host / $_want_port, as sharedServerHostBlock writes them) is left
// alone: it IS the run-time resolution, and removing it would leave the
// wrapper with no host at all.
func stripBakedServerPins(body string) (string, bool) {
	if !strings.Contains(body, "BEADS_DOLT_SERVER_") {
		return body, false
	}
	var out strings.Builder
	changed := false
	for _, line := range strings.SplitAfter(body, "\n") {
		trimmed := strings.TrimSpace(line)
		if bakedServerPinLineRe.MatchString(trimmed) && !resolvedHostValueRe.MatchString(trimmed) {
			changed = true
			continue
		}
		out.WriteString(line)
	}
	if !changed {
		return body, false
	}
	return out.String(), true
}

// homeRelativeValue maps an absolute path under the current user's home, or
// under any /Users/<x> or /home/<x> home, to its "$HOME/…" form.
func homeRelativeValue(v string) (string, bool) {
	var rest string
	if home, err := os.UserHomeDir(); err == nil && home != "" && home != "/" &&
		(v == home || strings.HasPrefix(v, home+"/")) {
		rest = v[len(home):]
	} else if m := foreignHomeRe.FindStringSubmatch(v); m != nil {
		rest = m[1]
	} else {
		return "", false
	}
	return `"$HOME` + pathEscaper.Replace(rest) + `"`, true
}

// relativizeWrapperHome rewrites only the BEADS_DIR and BRAIN_KNOWLEDGE_ROOT
// assignments that hold an absolute home path, leaving every other line,
// env pin, and the exec line untouched.
func relativizeWrapperHome(body string) (string, bool) {
	changed := false
	out := wrapperHomeVarRe.ReplaceAllStringFunc(body, func(m string) string {
		sub := wrapperHomeVarRe.FindStringSubmatch(m)
		v := sub[2]
		if v == "" {
			v = sub[3]
		}
		rel, ok := homeRelativeValue(v)
		if !ok {
			return m
		}
		changed = true
		return sub[1] + "=" + rel
	})
	return out, changed
}

// canonicalizeWrapperHost gives a wrapper the shared-host runtime block in place
// of any baked host pin. It is idempotent: an already-canonical wrapper with no
// baked pin is returned unchanged.
func canonicalizeWrapperHost(body string) (string, bool) {
	stripped, removedPin := stripBakedServerPins(body)
	changed := removedPin
	if strings.Contains(stripped, "_store_host_file=") {
		return stripped, changed
	}
	// Insert above the exec line so the block stays last-but-one and any
	// route/preflight lines above keep their order (the routing shim's own
	// comment requires host exports to sit below its probe).
	idx := strings.LastIndex(stripped, "\nexec ")
	if idx < 0 {
		if !strings.HasSuffix(stripped, "\n") {
			stripped += "\n"
		}
		return stripped + sharedServerHostBlock, true
	}
	return stripped[:idx+1] + sharedServerHostBlock + stripped[idx+1:], true
}

// plannedWrapper is what one wrapper should become: the body to write, whether
// it differs from what is there, and whether that difference repoints the store
// at the shared store-host record.
type plannedWrapper struct {
	path       string
	body       string
	exists     bool
	changed    bool
	repointed  bool
	generated  bool
	beadsDir   string
	dirMissing bool
	// BakedPin is true when the wrapper carried a BEADS_DOLT_SERVER_HOST/PORT
	// pin: a pin wins over the shared record, so a stale one is how a store
	// silently answers from (or fails against) the wrong server.
	BakedPin bool
	// Drifts lists, in operator words, why this wrapper does not read the
	// federation's one store-host record. Empty means it already does.
	Drifts []string
}

// wrapperPlanFor computes the target content for one wrapper. It never writes
// anything, so it is the same code path for a dry run and a real run: a dry run
// cannot report something the real run would not do.
func wrapperPlanFor(t wrapperTarget, bdBinary string) plannedWrapper {
	p := plannedWrapper{path: t.wrapper, beadsDir: t.beadsDir, exists: t.exists}
	if _, err := os.Stat(t.beadsDir); err != nil {
		p.dirMissing = true
	}
	if !t.exists {
		// 'brain stores rewrite-wrappers' generates the wrapper a registered
		// store is missing, so every registered store is reachable by the same
		// name it is registered under and no registry entry is wrapper-less
		// after a host has been converged.
		if t.serverMode {
			host, port, database := storeHostProvenance(t.entry)
			p.body = renderServerStoreWrapperBody(t.name, t.beadsDir, bdBinary, host, port, database)
		} else {
			p.body = renderStoreWrapperBody(t.name, t.beadsDir, bdBinary)
		}
		p.changed, p.generated, p.repointed = true, true, t.serverMode
		p.Drifts = append(p.Drifts, "store is registered but has no CLI wrapper")
		return p
	}

	current, err := os.ReadFile(t.wrapper) //nolint:gosec // the store's own wrapper
	if err != nil {
		// Unreadable wrapper: leave the plan empty and let the caller report it.
		p.body = ""
		p.changed = false
		return p
	}
	body := string(current)
	hadBlock := strings.Contains(body, "_store_host_file=")
	if _, removed := stripBakedServerPins(body); removed {
		p.BakedPin = true
	}
	body, homeChanged := relativizeWrapperHome(body)
	repointed := false
	if t.serverMode {
		body, repointed = canonicalizeWrapperHost(body)
	}
	// A pin-free but block-less server-mode wrapper is also drift: the store
	// resolves its host from somewhere other than the one record.
	if t.serverMode && !strings.Contains(body, "_store_host_file=") {
		repointed = true
	}
	p.body = body
	p.changed = homeChanged || repointed
	p.repointed = repointed
	switch {
	case p.BakedPin:
		p.Drifts = append(p.Drifts, "wrapper pins BEADS_DOLT_SERVER_HOST/PORT instead of reading the shared record")
	case t.serverMode && !hadBlock:
		p.Drifts = append(p.Drifts, "server-mode wrapper does not read the shared store host record")
	}
	if homeChanged {
		p.Drifts = append(p.Drifts, "wrapper carries a hardcoded home path")
	}
	return p
}

// storeHostProvenance is the host/port/database a regenerated wrapper names in
// its header comment. Values come from the shared record and the store's own
// metadata; "" / 0 means unknown and the header says so rather than inventing a
// server.
func storeHostProvenance(entry storeEntry) (host string, port int, database string) {
	if resolved, err := configfile.Resolve(); err == nil {
		host, port = resolved.Host, resolved.Port
	}
	if entry.Path != "" {
		beadsDir, _ := resolveStorePath(entry.Path)
		if cfg, err := configfile.Load(beadsDir); err == nil && cfg != nil {
			database = cfg.GetDoltDatabase()
		}
	}
	return host, port, database
}

// backupWrapper preserves the wrapper's previous content under
// ~/.local/state/brain/wrapper-backups/<run>/<name> and returns that path. One
// directory per run keeps a converged host's history scannable, and the state
// dir (not ~/.local/bin) keeps backups out of PATH.
func backupWrapper(path, run string) (string, error) {
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return "", fmt.Errorf("resolving home dir: %w", err)
	}
	data, err := os.ReadFile(path) //nolint:gosec // the store's own wrapper
	if err != nil {
		return "", fmt.Errorf("reading %s: %w", path, err)
	}
	info, err := os.Stat(path)
	if err != nil {
		return "", fmt.Errorf("stat %s: %w", path, err)
	}
	dir := filepath.Join(home, ".local", "state", "brain", "wrapper-backups", run)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", fmt.Errorf("mkdir %s: %w", dir, err)
	}
	dst := filepath.Join(dir, filepath.Base(path))
	if err := os.WriteFile(dst, data, info.Mode().Perm()); err != nil { //nolint:gosec // preserving the wrapper's own mode
		return "", fmt.Errorf("writing %s: %w", dst, err)
	}
	return dst, nil
}

// wrapperTarget is one wrapper this verb may rewrite or generate.
type wrapperTarget struct {
	name string
	// wrapper is the wrapper's path, whether or not it exists yet.
	wrapper string
	entry   storeEntry
	// beadsDir is this machine's resolved store path, used to generate a
	// missing wrapper and to fail loudly when the store itself is gone.
	beadsDir string
	exists   bool
	// serverMode is true when the store's own metadata.json declares the
	// shared server, i.e. the wrapper should resolve its host from the shared
	// store host config rather than from a baked pin. An embedded store keeps
	// its minimal wrapper.
	serverMode bool
}

// wrapperPathForStore returns the conventional wrapper path for a store name
// whether or not a file is there yet, plus whether a home directory resolved.
func wrapperPathForStore(name string) (string, bool) {
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return "", false
	}
	return filepath.Join(home, ".local", "bin", name), true
}

// collectWrapperTargets returns every registry store (whether or not it has a
// wrapper — a missing one is generated) plus every alias wrapper in
// ~/.local/bin (found by its generated header).
func collectWrapperTargets(stores map[string]storeEntry) []wrapperTarget {
	var targets []wrapperTarget
	seen := map[string]bool{}
	for _, name := range sortedKeys(stores) {
		wp, ok := wrapperPathForStore(name)
		if !ok {
			continue
		}
		// A forwarding wrapper ('brain remote install') hands the command to
		// another machine and never opens a store here: rewriting or replacing
		// it would break the forwarding it exists for.
		if isRemoteWrapper(wp) {
			seen[name] = true
			continue
		}
		beadsDir, _ := resolveStorePath(stores[name].Path)
		seen[name] = true
		_, statErr := os.Stat(wp)
		if statErr != nil && remoteClientHost() != "" {
			// A client reaches its stores through forwarding wrappers written
			// by 'brain remote install'. Generating a local store wrapper here
			// would point the command at a store this machine does not serve,
			// so a missing wrapper is left to the client verb that owns it —
			// and 'brain doctor' reports it (registry-vs-wrapper census).
			continue
		}
		targets = append(targets, wrapperTarget{
			name:       name,
			wrapper:    wp,
			entry:      stores[name],
			beadsDir:   beadsDir,
			exists:     statErr == nil,
			serverMode: serverModeForEntry(stores[name]),
		})
	}
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return targets
	}
	binDir := filepath.Join(home, ".local", "bin")
	ents, err := os.ReadDir(binDir)
	if err != nil {
		return targets
	}
	for _, e := range ents {
		if e.IsDir() || seen[e.Name()] {
			continue
		}
		wp, ok := storeWrapperPath(e.Name())
		if !ok {
			continue
		}
		data, err := os.ReadFile(wp)
		if err != nil || !strings.Contains(string(data), aliasWrapperHeader) {
			continue
		}
		entry := storeEntry{}
		if m := wrapperBeadsRe.FindStringSubmatch(string(data)); m != nil {
			entry.Path = expandWrapperHome(m[1])
		}
		self, canon := canonicalWrapperFor(e.Name(), wp, entry, serverModeForEntry(entry))
		if canon {
			targets = append(targets, self)
		}
	}
	return targets
}

// canonicalWrapperFor builds the rewrite target for one wrapper, or reports
// false when the wrapper is one this verb must not touch (a forwarding wrapper
// installed by 'brain remote install').
func canonicalWrapperFor(name, wrapperPath string, entry storeEntry, serverMode bool) (wrapperTarget, bool) {
	if isRemoteWrapper(wrapperPath) {
		return wrapperTarget{}, false
	}
	beadsDir, _ := resolveStorePath(entry.Path)
	return wrapperTarget{name: name, wrapper: wrapperPath, entry: entry, beadsDir: beadsDir, exists: true, serverMode: serverMode}, true
}

// serverModeForEntry reports whether the store's own metadata.json declares the
// shared Dolt sql-server (never an embedded, self-starting store).
func serverModeForEntry(entry storeEntry) bool {
	if entry.Path == "" {
		return false
	}
	beadsDir, _ := resolveStorePath(entry.Path)
	cfg, err := configfile.Load(beadsDir)
	if err != nil || cfg == nil {
		return false
	}
	return strings.EqualFold(cfg.DoltMode, configfile.DoltModeServer)
}

// rewriteRunOptions is one convergence run: what to converge, how much
// concurrency, and whether it is allowed to write.
type rewriteRunOptions struct {
	self     string
	stores   map[string]storeEntry
	jobs     int
	timeout  time.Duration
	dryRun   bool
	backup   bool
	bdBinary string
}

// rewriteAllStoreWrappers converges every store and alias wrapper: home paths
// become $HOME-relative, server-mode wrappers resolve their Dolt host from the
// shared store host record, and a registered store without a wrapper gets the
// canonical one. Each wrapper is then verified by reading through it, so a
// wrapper that cannot resolve a database is reported rather than assumed good.
func rewriteAllStoreWrappers(opts rewriteRunOptions) []wrapperRewrite {
	targets := collectWrapperTargets(opts.stores)
	results := make([]wrapperRewrite, len(targets))
	if opts.jobs < 1 {
		opts.jobs = 1
	}
	if opts.bdBinary == "" {
		opts.bdBinary = "bd"
	}
	run := time.Now().Format("20060102-150405")
	sem := make(chan struct{}, opts.jobs)
	var wg sync.WaitGroup
	for i, t := range targets {
		wg.Add(1)
		sem <- struct{}{}
		go func(i int, t wrapperTarget) {
			defer wg.Done()
			defer func() { <-sem }()
			results[i] = rewriteOneWrapper(opts, run, t)
		}(i, t)
	}
	wg.Wait()
	return results
}

// rewriteOneWrapper plans (and, unless this is a dry run, applies) one
// wrapper's convergence, then verifies it by reading through it.
func rewriteOneWrapper(opts rewriteRunOptions, run string, t wrapperTarget) wrapperRewrite {
	r := wrapperRewrite{Name: t.name, Wrapper: t.wrapper, DryRun: opts.dryRun}
	plan := wrapperPlanFor(t, opts.bdBinary)
	r.Generated, r.Repointed, r.Changed = plan.generated, plan.repointed, plan.changed
	r.WouldWrite = opts.dryRun && plan.changed

	if plan.dirMissing && plan.generated {
		r.Status = "fail"
		r.Reason = fmt.Sprintf("no store directory at %s, so its wrapper was not generated (create the store or fix the registry path)", t.beadsDir)
		return r
	}
	if plan.exists && plan.body == "" {
		r.Status = "fail"
		r.Reason = "reading the existing wrapper failed"
		return r
	}

	if !opts.dryRun && plan.changed {
		if plan.exists && opts.backup {
			backup, err := backupWrapper(t.wrapper, run)
			if err != nil {
				r.Status = "fail"
				r.Reason = "backing up the wrapper: " + err.Error()
				return r
			}
			r.Backup = backup
		}
		if err := os.MkdirAll(filepath.Dir(t.wrapper), 0o755); err != nil {
			r.Status = "fail"
			r.Reason = "creating the wrapper directory: " + err.Error()
			return r
		}
		if err := os.WriteFile(t.wrapper, []byte(plan.body), 0o755); err != nil { //nolint:gosec // wrappers are executable
			r.Status = "fail"
			r.Reason = "writing the wrapper: " + err.Error()
			return r
		}
	}

	h := probeStore(opts.self, t.name, t.entry, opts.timeout)
	switch {
	case h.Status == "fail":
		r.Status, r.Reason = "fail", "wrapper does not resolve a database: "+h.Reason
	case h.Probe != "wrapper":
		r.Status, r.Reason = "fail", "wrapper not executable after rewrite"
	default:
		r.Status = "ok"
	}
	return r
}

func failedRewrites(rs []wrapperRewrite) []wrapperRewrite {
	var out []wrapperRewrite
	for _, r := range rs {
		if r.Status != "ok" {
			out = append(out, r)
		}
	}
	return out
}

var brainStoresRewriteWrappersCmd = &cobra.Command{
	Use:   "rewrite-wrappers",
	Short: "Generate/repoint every store CLI wrapper from the shared store-host record, and verify each resolves a database",
	Long: `Converges this machine's store wrappers on the federation's one store-host
record:

  - every registered store WITHOUT a wrapper gets the canonical wrapper
    (~/.local/bin/<name>), so a store is reachable under the name it is
    registered under and the registry has no wrapper-less entry;
  - each existing wrapper's BEADS_DIR and BRAIN_KNOWLEDGE_ROOT lines become
    "$HOME/…", preserving every other env pin and the exec line;
  - a server-mode store's wrapper is repointed at the shared store host config
    (~/.config/brain/store-host.env): the run-time host block is added when
    missing and any baked BEADS_DOLT_SERVER_HOST/PORT pin is dropped, because a
    leftover pin would win over the record. Embedded stores keep their minimal
    wrapper, and forwarding wrappers installed by 'brain remote install' are
    left alone;
  - registry entries recorded under another machine's home are healed to this
    machine's equivalent and persisted.

Every wrapper that changes is backed up first, under
~/.local/state/brain/wrapper-backups/<run>/, so a machine can be un-converged.
Each wrapper is then read through the way 'brain stores doctor' does.

--dry-run reports what would change (and still reads every wrapper through)
without writing anything: no wrapper, no registry, no backup.

This is the one step that converges a host's stores on the federation's shared
server. 'brain remote set' and 'brain remote install' run it on the brain host
and fail when a store still cannot resolve a database.`,
	Args: cobra.NoArgs,
	Run: func(cmd *cobra.Command, _ []string) {
		stores, err := loadStoresRegistry()
		if err != nil {
			FatalError("loading registry: %v", err)
		}
		results, healed, err := convergeStoreWrappers(rewriteRunOptions{
			self:     selfBinary(),
			stores:   stores,
			jobs:     storesRewriteJobs,
			timeout:  storesRewriteTimeout,
			dryRun:   storesRewriteDryRun,
			backup:   storesRewriteBackup,
			bdBinary: storesRewriteBdBinary,
		})
		if err != nil {
			FatalError("%v", err)
		}
		failed := failedRewrites(results)
		repointed, generated := 0, 0
		for _, r := range results {
			if r.Repointed {
				repointed++
			}
			if r.Generated {
				generated++
			}
		}

		if jsonOutput {
			if err := outputJSON(map[string]any{
				"total":     len(results),
				"failed":    len(failed),
				"repointed": repointed,
				"generated": generated,
				"healed":    healed,
				"dry_run":   storesRewriteDryRun,
				"stores":    results,
			}); err != nil {
				FatalError("encoding results: %v", err)
			}
		} else {
			for _, r := range results {
				if r.Status != "ok" {
					fmt.Printf("  FAIL  %-18s %s\n", r.Name, r.Reason)
					continue
				}
				var notes []string
				if r.Generated {
					notes = append(notes, "generated")
				}
				if r.Repointed {
					notes = append(notes, "host now read from the shared store host config")
				}
				if r.DryRun && r.WouldWrite {
					notes = append(notes, "dry-run: would rewrite")
				}
				if r.Backup != "" {
					notes = append(notes, "backup "+r.Backup)
				}
				note := ""
				if len(notes) > 0 {
					note = "  (" + strings.Join(notes, "; ") + ")"
				}
				fmt.Printf("  ok    %-18s %s%s\n", r.Name, r.Wrapper, note)
			}
			mode := ""
			if storesRewriteDryRun {
				mode = " [dry run: nothing written]"
			}
			fmt.Printf("%d/%d wrappers verified (%d repointed, %d generated)%s\n",
				len(results)-len(failed), len(results), repointed, generated, mode)
			if len(healed) > 0 {
				fmt.Printf("healed %d registry path(s) recorded under another home: %s\n", len(healed), strings.Join(healed, " "))
			}
		}
		if len(failed) > 0 {
			var n []string
			for _, r := range failed {
				n = append(n, r.Name)
			}
			sort.Strings(n)
			fmt.Fprintf(os.Stderr, "FAILING STORES: %s\n", strings.Join(n, " "))
			os.Exit(1)
		}
	},
}

// convergeStoreWrappers is the one convergence path: it heals registry paths
// (only when it may write), then rewrites/generates and verifies every wrapper.
// 'brain stores rewrite-wrappers' and 'brain stores doctor --fix' both call it,
// so a repair can never do a different thing than the verb that reports it.
func convergeStoreWrappers(opts rewriteRunOptions) ([]wrapperRewrite, []string, error) {
	stores := opts.stores
	var healed []string
	if !opts.dryRun {
		h, err := persistHealedRegistryPaths()
		if err != nil {
			return nil, nil, fmt.Errorf("persisting healed registry paths: %w", err)
		}
		healed = h
	} else {
		// A dry run still reports the healing it would persist.
		recorded, err := loadRawStoresRegistry()
		if err != nil {
			return nil, nil, fmt.Errorf("loading registry: %w", err)
		}
		healRegistryPaths(recorded)
		for _, name := range sortedKeys(recorded) {
			if recorded[name].Path != stores[name].Path {
				healed = append(healed, name)
			}
		}
	}
	return rewriteAllStoreWrappers(opts), healed, nil
}

// selfBinary is this process's own path, used to probe wrappers with the binary
// under test rather than whatever 'bd' PATH resolves to.
func selfBinary() string {
	self, err := os.Executable()
	if err != nil || self == "" {
		return os.Args[0]
	}
	return self
}

// verifyHostWrappers runs 'brain stores rewrite-wrappers' on the host and
// returns an error listing every store whose wrapper failed. It is the gate
// behind 'brain remote set' and 'brain remote install': a host whose wrappers
// cannot resolve a database must not look successfully configured.
func verifyHostWrappers(ctx context.Context, cfg *remoteConfig) (total int, err error) {
	out, runErr := remoteCapture(ctx, cfg, "brain", "stores", "rewrite-wrappers", "--json")
	results, perr := parseRewriteResults(out)
	if perr != nil {
		if runErr != nil {
			return 0, fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, runErr)
		}
		return 0, fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, perr)
	}
	if failed := failedRewrites(results); len(failed) > 0 {
		var b strings.Builder
		fmt.Fprintf(&b, "%d of %d store wrappers on %s failed to resolve a database:", len(failed), len(results), cfg.Host)
		for _, r := range failed {
			fmt.Fprintf(&b, "\n  %s: %s", r.Name, r.Reason)
		}
		return len(results), fmt.Errorf("%s", b.String())
	}
	if runErr != nil {
		return len(results), fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, runErr)
	}
	return len(results), nil
}

func parseRewriteResults(data []byte) ([]wrapperRewrite, error) {
	start := strings.Index(string(data), "{")
	if start < 0 {
		return nil, fmt.Errorf("host printed no JSON result: %q", strings.TrimSpace(string(data)))
	}
	var payload struct {
		Stores []wrapperRewrite `json:"stores"`
	}
	if err := json.Unmarshal(data[start:], &payload); err != nil {
		return nil, fmt.Errorf("parsing host result: %w", err)
	}
	return payload.Stores, nil
}

