// wrapperRewrite is the outcome for one wrapper: its home path was made
// $HOME-relative in place and it was then read through (the same probe
// 'brain stores doctor' uses).
type wrapperRewrite struct {
	Name    string `json:"name"`
	Wrapper string `json:"wrapper,omitempty"`
	Status  string `json:"status"` // "ok" | "fail"
	Reason  string `json:"reason,omitempty"`
}

const aliasWrapperHeader = "# Auto-generated by 'brain stores alias "

var (
	wrapperHomeVarRe = regexp.MustCompile(`\b(BEADS_DIR|BRAIN_KNOWLEDGE_ROOT)=(?:"([^"]*)"|([^\s"]+))`)
	foreignHomeRe    = regexp.MustCompile(`^/(?:Users|home)/[^/]+(/.*)?$`)
	wrapperBeadsRe   = regexp.MustCompile(`\bBEADS_DIR="?([^"\s]+)"?`)
	pathEscaper      = strings.NewReplacer(`\`, `\\`, `"`, `\"`, "$", `\$`, "`", "\\`")
)

// homeRelativeValue maps an absolute path under the current user's home, or
// under any /Users/<x> or /home/<x> home, to its "$HOME/…" form.
func homeRelativeValue(v string) (string, bool) {
	var rest string
	if home, err := os.UserHomeDir(); err == nil && home != "" && home != "/" &&
		(v == home || strings.HasPrefix(v, home+"/")) {
		rest = v[len(home):]
	} else if m := foreignHomeRe.FindStringSubmatch(v); m != nil {
		rest = m[1]
	} else {
		return "", false
	}
	return `"$HOME` + pathEscaper.Replace(rest) + `"`, true
}

// relativizeWrapperHome rewrites only the BEADS_DIR and BRAIN_KNOWLEDGE_ROOT
// assignments that hold an absolute home path, leaving every other line,
// env pin, and the exec line untouched.
func relativizeWrapperHome(body string) (string, bool) {
	changed := false
	out := wrapperHomeVarRe.ReplaceAllStringFunc(body, func(m string) string {
		sub := wrapperHomeVarRe.FindStringSubmatch(m)
		v := sub[2]
		if v == "" {
			v = sub[3]
		}
		rel, ok := homeRelativeValue(v)
		if !ok {
			return m
		}
		changed = true
		return sub[1] + "=" + rel
	})
	return out, changed
}

// rewriteWrapperInPlace makes an existing wrapper's home paths $HOME-relative.
func rewriteWrapperInPlace(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	out, changed := relativizeWrapperHome(string(data))
	if !changed {
		return nil
	}
	info, err := os.Stat(path)
	if err != nil {
		return err
	}
	return os.WriteFile(path, []byte(out), info.Mode().Perm()) //nolint:gosec // preserving the wrapper's own mode
}

// wrapperTarget is one existing wrapper to rewrite and verify.
type wrapperTarget struct {
	name  string
	entry storeEntry
}

// collectWrapperTargets returns every registry store that has a wrapper plus
// every alias wrapper in ~/.local/bin (found by its generated header).
// Registered stores with no wrapper (--no-wrapper) are skipped.
func collectWrapperTargets(stores map[string]storeEntry) []wrapperTarget {
	var targets []wrapperTarget
	seen := map[string]bool{}
	for _, name := range sortedKeys(stores) {
		if _, ok := storeWrapperPath(name); ok {
			targets = append(targets, wrapperTarget{name, stores[name]})
			seen[name] = true
		}
	}
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return targets
	}
	binDir := filepath.Join(home, ".local", "bin")
	ents, err := os.ReadDir(binDir)
	if err != nil {
		return targets
	}
	for _, e := range ents {
		if e.IsDir() || seen[e.Name()] {
			continue
		}
		if _, ok := storeWrapperPath(e.Name()); !ok {
			continue
		}
		data, err := os.ReadFile(filepath.Join(binDir, e.Name()))
		if err != nil || !strings.Contains(string(data), aliasWrapperHeader) {
			continue
		}
		entry := storeEntry{}
		if m := wrapperBeadsRe.FindStringSubmatch(string(data)); m != nil {
			entry.Path = strings.Replace(m[1], "$HOME", home, 1)
		}
		targets = append(targets, wrapperTarget{e.Name(), entry})
	}
	return targets
}

// rewriteAllStoreWrappers makes every existing store and alias wrapper
// $HOME-relative in place, then verifies each by reading through it. A wrapper
// counts as ok only when it resolves a database.
func rewriteAllStoreWrappers(self string, stores map[string]storeEntry, jobs int, timeout time.Duration) []wrapperRewrite {
	targets := collectWrapperTargets(stores)
	results := make([]wrapperRewrite, len(targets))
	if jobs < 1 {
		jobs = 1
	}
	sem := make(chan struct{}, jobs)
	var wg sync.WaitGroup
	for i, t := range targets {
		wg.Add(1)
		sem <- struct{}{}
		go func(i int, t wrapperTarget) {
			defer wg.Done()
			defer func() { <-sem }()
			r := wrapperRewrite{Name: t.name}
			wp, _ := storeWrapperPath(t.name)
			r.Wrapper = wp
			if err := rewriteWrapperInPlace(wp); err != nil {
				r.Status, r.Reason = "fail", "rewriting wrapper: "+err.Error()
				results[i] = r
				return
			}
			h := probeStore(self, t.name, t.entry, timeout)
			switch {
			case h.Status == "fail":
				r.Status, r.Reason = "fail", "wrapper does not resolve a database: "+h.Reason
			case h.Probe != "wrapper":
				r.Status, r.Reason = "fail", "wrapper not executable after rewrite"
			default:
				r.Status = "ok"
			}
			results[i] = r
		}(i, t)
	}
	wg.Wait()
	return results
}

func failedRewrites(rs []wrapperRewrite) []wrapperRewrite {
	var out []wrapperRewrite
	for _, r := range rs {
		if r.Status != "ok" {
			out = append(out, r)
		}
	}
	return out
}

var brainStoresRewriteWrappersCmd = &cobra.Command{
	Use:   "rewrite-wrappers",
	Short: "Make every store/alias CLI wrapper $HOME-relative in place and verify each resolves a database",
	Long: `Rewrites the BEADS_DIR and BRAIN_KNOWLEDGE_ROOT lines of each existing
~/.local/bin wrapper (registered stores and 'brain stores alias' wrappers) to
"$HOME/…" in place, preserving every other env pin and the exec line. Stores
with no wrapper are skipped. Each wrapper is then read through the way
'brain stores doctor' does.

Exits non-zero, naming every store that failed, if any wrapper cannot be
written or does not resolve a database. 'brain remote set' and
'brain remote install' run this on the brain host.`,
	Args: cobra.NoArgs,
	Run: func(cmd *cobra.Command, _ []string) {
		stores, err := loadStoresRegistry()
		if err != nil {
			FatalError("loading registry: %v", err)
		}
		self, err := os.Executable()
		if err != nil || self == "" {
			self = os.Args[0]
		}
		results := rewriteAllStoreWrappers(self, stores, storesRewriteJobs, storesRewriteTimeout)
		failed := failedRewrites(results)
		if jsonOutput {
			outputJSON(map[string]any{"total": len(results), "failed": len(failed), "stores": results})
		} else {
			for _, r := range results {
				if r.Status == "ok" {
					fmt.Printf("  ok    %-18s %s\n", r.Name, r.Wrapper)
				} else {
					fmt.Printf("  FAIL  %-18s %s\n", r.Name, r.Reason)
				}
			}
			fmt.Printf("%d/%d wrappers rewritten and verified\n", len(results)-len(failed), len(results))
		}
		if len(failed) > 0 {
			var n []string
			for _, r := range failed {
				n = append(n, r.Name)
			}
			sort.Strings(n)
			fmt.Fprintf(os.Stderr, "FAILING STORES: %s\n", strings.Join(n, " "))
			os.Exit(1)
		}
	},
}

// verifyHostWrappers runs 'brain stores rewrite-wrappers' on the host and
// returns an error listing every store whose wrapper failed. It is the gate
// behind 'brain remote set' and 'brain remote install': a host whose wrappers
// cannot resolve a database must not look successfully configured.
func verifyHostWrappers(ctx context.Context, cfg *remoteConfig) (total int, err error) {
	out, runErr := remoteCapture(ctx, cfg, "brain", "stores", "rewrite-wrappers", "--json")
	results, perr := parseRewriteResults(out)
	if perr != nil {
		if runErr != nil {
			return 0, fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, runErr)
		}
		return 0, fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, perr)
	}
	if failed := failedRewrites(results); len(failed) > 0 {
		var b strings.Builder
		fmt.Fprintf(&b, "%d of %d store wrappers on %s failed to resolve a database:", len(failed), len(results), cfg.Host)
		for _, r := range failed {
			fmt.Fprintf(&b, "\n  %s: %s", r.Name, r.Reason)
		}
		return len(results), fmt.Errorf("%s", b.String())
	}
	if runErr != nil {
		return len(results), fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, runErr)
	}
	return len(results), nil
}

func parseRewriteResults(data []byte) ([]wrapperRewrite, error) {
	start := strings.Index(string(data), "{")
	if start < 0 {
		return nil, fmt.Errorf("host printed no JSON result: %q", strings.TrimSpace(string(data)))
	}
	var payload struct {
		Stores []wrapperRewrite `json:"stores"`
	}
	if err := json.Unmarshal(data[start:], &payload); err != nil {
		return nil, fmt.Errorf("parsing host result: %w", err)
	}
	return payload.Stores, nil
}

