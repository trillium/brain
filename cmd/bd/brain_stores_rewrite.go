// wrapperRewrite is the outcome for one wrapper: its home path was made
// $HOME-relative in place and it was then read through (the same probe
// 'brain stores doctor' uses).
type wrapperRewrite struct {
	Name    string `json:"name"`
	Wrapper string `json:"wrapper,omitempty"`
	Status  string `json:"status"` // "ok" | "unclassified" | "fail"
	Reason  string `json:"reason,omitempty"`
	// Repointed is true when the wrapper was rewritten to resolve its Dolt
	// host from the shared store host config at run time (a baked host pin was
	// dropped or the runtime block was added).
	Repointed bool `json:"repointed,omitempty"`
}

const aliasWrapperHeader = "# Auto-generated by 'brain stores alias "

var (
	wrapperHomeVarRe = regexp.MustCompile(`\b(BEADS_DIR|BRAIN_KNOWLEDGE_ROOT)=(?:"([^"]*)"|([^\s"]+))`)
	foreignHomeRe    = regexp.MustCompile(`^/(?:Users|home)/[^/]+(/.*)?$`)
	pathEscaper      = strings.NewReplacer(`\`, `\\`, `"`, `\"`, "$", `\$`, "`", "\\`")

	// The wrapper*AssignRe patterns match an effective assignment of a wrapper
	// variable, with or without `export`, anywhere on a line. A read such as
	// "${BEADS_DOLT_SERVER_HOST:-}" or "$BEADS_DIR" is not an assignment.
	wrapperBeadsAssignRe = assignmentRe("BEADS_DIR")
	wrapperHostAssignRe  = assignmentRe(configfile.StoreHostKeyHost)
	wrapperPortAssignRe  = assignmentRe(configfile.StoreHostKeyPort)

	// strippableServerPinRe matches a line that is nothing but a baked host/port
	// pin, so the whole line can be dropped. A pin inside a conditional or a
	// command list is only detected, never rewritten.
	strippableServerPinRe = regexp.MustCompile(`^(?:export\s+)?BEADS_DOLT_SERVER_(?:HOST|PORT)=[^\s;]+$`)

	// wrapperQuoteTrim is the set of shell quoting characters a wrapper value
	// may carry around a path.
	wrapperQuoteTrim = "\"'" + "`"
)

func assignmentRe(name string) *regexp.Regexp {
	return regexp.MustCompile(`(?:^|[;\s])(?:export\s+)?` + regexp.QuoteMeta(name) + `=([^\s;#]*)`)
}

// homeRelativeValue maps an absolute path under the current user's home, or
// under any /Users/<x> or /home/<x> home, to its "$HOME/…" form.
func homeRelativeValue(v string) (string, bool) {
	var rest string
	if home, err := os.UserHomeDir(); err == nil && home != "" && home != "/" &&
		(v == home || strings.HasPrefix(v, home+"/")) {
		rest = v[len(home):]
	} else if m := foreignHomeRe.FindStringSubmatch(v); m != nil {
		rest = m[1]
	} else {
		return "", false
	}
	return `"$HOME` + pathEscaper.Replace(rest) + `"`, true
}

// relativizeWrapperHome rewrites only the BEADS_DIR and BRAIN_KNOWLEDGE_ROOT
// assignments that hold an absolute home path, leaving every other line,
// env pin, and the exec line untouched.
func relativizeWrapperHome(body string) (string, bool) {
	changed := false
	out := wrapperHomeVarRe.ReplaceAllStringFunc(body, func(m string) string {
		sub := wrapperHomeVarRe.FindStringSubmatch(m)
		v := sub[2]
		if v == "" {
			v = sub[3]
		}
		rel, ok := homeRelativeValue(v)
		if !ok {
			return m
		}
		changed = true
		return sub[1] + "=" + rel
	})
	return out, changed
}

// wrapperBackupSuffix names the copy 'brain stores rewrite-wrappers' leaves of a
// wrapper before it is rewritten, so an operator can restore it if the repoint
// must be rolled back.
const wrapperBackupSuffix = ".bak"

// rewriteWrapperInPlace makes an existing wrapper's home paths $HOME-relative,
// and — for a store whose metadata.json declares server mode — makes it resolve
// the Dolt host from the shared store host config at run time: the runtime block
// is added when missing and baked host/port pins are dropped, since a leftover
// pin would win over the file. Every other line (route sourcing, comments) is
// preserved. The pre-rewrite file is copied to <path>.bak first, so the change
// is reversible.
func rewriteWrapperInPlace(path string, serverMode bool) (repointed bool, err error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	out, changed := relativizeWrapperHome(string(data))
	if serverMode {
		var canonical bool
		out, canonical = canonicalizeWrapperHost(out)
		changed = changed || canonical
		repointed = canonical
	}
	if !changed {
		return false, nil
	}
	info, err := os.Stat(path)
	if err != nil {
		return repointed, err
	}
	if err := os.WriteFile(path+wrapperBackupSuffix, data, info.Mode().Perm()); err != nil { //nolint:gosec // the wrapper's own backup
		return repointed, fmt.Errorf("writing %s: %w", path+wrapperBackupSuffix, err)
	}
	return repointed, os.WriteFile(path, []byte(out), info.Mode().Perm()) //nolint:gosec // preserving the wrapper's own mode
}

// canonicalizeWrapperHost gives a wrapper the shared-host runtime block in place
// of any baked host pin. It is idempotent: an already-canonical wrapper with no
// baked pin is returned unchanged.
func canonicalizeWrapperHost(body string) (string, bool) {
	stripped := stripBakedServerPins(body)
	changed := stripped != body
	if strings.Contains(stripped, "_store_host_file=") {
		return stripped, changed
	}
	idx := wrapperHostBlockOffset(stripped)
	return stripped[:idx] + sharedServerHostBlock + stripped[idx:], true
}

// wrapperHostBlockOffset is where the run-time host block must be inserted:
// after the shebang, the leading comment block and any route-sourcing lines,
// and before the first statement that can reach a bd invocation. The block has
// to run before every bd call in the wrapper, not just the last exec.
func wrapperHostBlockOffset(body string) int {
	offset := 0
	for _, line := range strings.SplitAfter(body, "\n") {
		trimmed := strings.TrimSpace(line)
		isRouteSource := strings.HasPrefix(trimmed, ". ") || trimmed == "." || strings.HasPrefix(trimmed, "source ")
		if trimmed == "" || strings.HasPrefix(trimmed, "#") || isRouteSource {
			offset += len(line)
			continue
		}
		break
	}
	return offset
}

// lineAssignedValue returns the value an effective line assigns to the variable
// re matches, or ok=false when the line only reads it or names it in prose
// inside a quoted string.
func lineAssignedValue(line string, re *regexp.Regexp) (string, bool) {
	for _, loc := range re.FindAllStringSubmatchIndex(line, -1) {
		if insideShellQuotes(line, loc[2]) {
			continue
		}
		return strings.Trim(line[loc[2]:loc[3]], wrapperQuoteTrim), true
	}
	return "", false
}

// insideShellQuotes reports whether pos in line sits inside a quoted shell
// string, so a key named in an echo or a comment is not read as an assignment.
func insideShellQuotes(line string, pos int) bool {
	double, single := false, false
	for i := 0; i < pos && i < len(line); i++ {
		switch line[i] {
		case '\\':
			if !single {
				i++
			}
		case '\'':
			if !double {
				single = !single
			}
		case '"':
			if !single {
				double = !double
			}
		}
	}
	return double || single
}

// wrapperAssignedValue returns the value the wrapper body assigns to the
// variable re matches on its first effective (non-comment) line, so a comment
// documenting an override is never mistaken for the wrapper's own pin.
func wrapperAssignedValue(body string, re *regexp.Regexp) (string, bool) {
	for _, line := range strings.SplitAfter(body, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "#") {
			continue
		}
		if v, ok := lineAssignedValue(line, re); ok {
			return v, true
		}
	}
	return "", false
}

// bakedServerPinLine reports whether a wrapper line assigns a literal Dolt host
// or port, in whatever shape the wrapper wrote it. The runtime block's own two
// exports read $_want_ and so are the resolution this verb exists to install,
// not a baked pin; a bare `export NAME` with no value is not a pin either.
func bakedServerPinLine(line string) bool {
	if strings.HasPrefix(strings.TrimSpace(line), "#") || strings.Contains(line, "$_want_") {
		return false
	}
	for _, re := range []*regexp.Regexp{wrapperHostAssignRe, wrapperPortAssignRe} {
		if _, ok := lineAssignedValue(line, re); ok {
			return true
		}
	}
	return false
}

// stripBakedServerPins drops the pure-assignment host/port pins older wrappers
// baked in. A pin inside a conditional or a command list is left alone:
// arbitrary shell cannot be rewritten safely, so the post-rewrite check reports
// it as a failure instead.
func stripBakedServerPins(body string) string {
	var b strings.Builder
	for _, line := range strings.SplitAfter(body, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "#") && !strings.Contains(line, "$_want_") && strippableServerPinRe.MatchString(trimmed) {
			continue
		}
		b.WriteString(line)
	}
	return b.String()
}

// wrapperTarget is one existing wrapper to rewrite and verify.
type wrapperTarget struct {
	name  string
	entry storeEntry
	// serverMode is true when the wrapper should resolve its host from the
	// shared store host config rather than from a baked pin: its own store
	// declares the shared server, or it already carries a baked server pin.
	// An embedded store keeps its minimal wrapper.
	serverMode bool
	// classified is false when neither the wrapper's own store's metadata.json
	// nor a baked pin says which shape this wrapper is. Such a wrapper is
	// reported as unclassified, never as repointed or ok.
	classified bool
}

// collectWrapperTargets returns every registry store that has a wrapper plus
// every alias wrapper in ~/.local/bin (found by its generated header).
// Registered stores with no wrapper (--no-wrapper) are skipped.
func collectWrapperTargets(stores map[string]storeEntry) []wrapperTarget {
	var targets []wrapperTarget
	seen := map[string]bool{}
	for _, name := range sortedKeys(stores) {
		wp, ok := storeWrapperPath(name)
		if !ok {
			continue
		}
		// A forwarding wrapper ('brain remote install') hands the command to
		// another machine and never opens a store here: rewriting it would
		// break the forwarding it exists for.
		self, canon := canonicalWrapperFor(name, wp, stores[name])
		seen[name] = true
		if !canon {
			continue
		}
		self.serverMode, self.classified = classifyWrapper(stores[name], wp)
		targets = append(targets, self)
	}
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return targets
	}
	binDir := filepath.Join(home, ".local", "bin")
	ents, err := os.ReadDir(binDir)
	if err != nil {
		return targets
	}
	for _, e := range ents {
		if e.IsDir() || seen[e.Name()] || strings.HasSuffix(e.Name(), wrapperBackupSuffix) {
			continue
		}
		wp, ok := storeWrapperPath(e.Name())
		if !ok {
			continue
		}
		data, err := os.ReadFile(wp)
		if err != nil || !strings.Contains(string(data), aliasWrapperHeader) {
			continue
		}
		entry := storeEntry{}
		if beadsDir, ok := wrapperBeadsDir(wp); ok {
			entry.Path = beadsDir
		}
		self, canon := canonicalWrapperFor(e.Name(), wp, entry)
		if canon {
			self.serverMode, self.classified = classifyWrapper(entry, wp)
			targets = append(targets, self)
		}
	}
	return targets
}

// canonicalWrapperFor builds the rewrite target for one wrapper, or reports
// false when the wrapper is one this verb must not touch (a forwarding wrapper
// installed by 'brain remote install').
func canonicalWrapperFor(name, wrapperPath string, entry storeEntry) (wrapperTarget, bool) {
	if isRemoteWrapper(wrapperPath) {
		return wrapperTarget{}, false
	}
	return wrapperTarget{name: name, entry: entry}, true
}

// classifyWrapper decides whether a wrapper should resolve its host from the
// shared store host config, the way 'brain stores doctor' identifies a store:
// from the wrapper's own BEADS_DIR first, then the registry path. A wrapper
// that already carries a baked host pin is a shared-server wrapper whatever its
// store's metadata says. classified is false when neither answers, so the verb
// reports the wrapper instead of counting it repointed.
func classifyWrapper(entry storeEntry, wrapperPath string) (serverMode, classified bool) {
	if _, found := bakedServerPinIn(wrapperPath); found {
		return true, true
	}
	paths := make([]string, 0, 2)
	if beadsDir, ok := wrapperBeadsDir(wrapperPath); ok {
		paths = append(paths, beadsDir)
	}
	if entry.Path != "" {
		paths = append(paths, expandPath(entry.Path))
	}
	for _, beadsDir := range paths {
		cfg, err := configfile.Load(beadsDir)
		if err != nil || cfg == nil {
			continue
		}
		return strings.EqualFold(cfg.DoltMode, configfile.DoltModeServer), true
	}
	return false, false
}

// bakedServerPinIn reports the first baked host/port pin a wrapper carries.
func bakedServerPinIn(wrapperPath string) (string, bool) {
	data, err := os.ReadFile(wrapperPath) //nolint:gosec // the store's own wrapper
	if err != nil {
		return "", false
	}
	for _, line := range strings.SplitAfter(string(data), "\n") {
		if bakedServerPinLine(line) {
			return strings.TrimSpace(line), true
		}
	}
	return "", false
}

// rewriteAllStoreWrappers makes every existing store and alias wrapper
// $HOME-relative in place, then verifies each by reading through it. A wrapper
// counts as ok only when it resolves a database.
func rewriteAllStoreWrappers(self string, stores map[string]storeEntry, jobs int, timeout time.Duration) []wrapperRewrite {
	targets := collectWrapperTargets(stores)
	results := make([]wrapperRewrite, len(targets))
	if jobs < 1 {
		jobs = 1
	}
	sem := make(chan struct{}, jobs)
	var wg sync.WaitGroup
	for i, t := range targets {
		wg.Add(1)
		sem <- struct{}{}
		go func(i int, t wrapperTarget) {
			defer wg.Done()
			defer func() { <-sem }()
			r := wrapperRewrite{Name: t.name}
			wp, _ := storeWrapperPath(t.name)
			r.Wrapper = wp
			repointed, err := rewriteWrapperInPlace(wp, t.serverMode)
			r.Repointed = repointed
			if err != nil {
				r.Status, r.Reason = "fail", "rewriting wrapper: "+err.Error()
				results[i] = r
				return
			}
			if pin, found := bakedServerPinIn(wp); found {
				r.Status, r.Reason = "fail", "baked Dolt host pin remains: "+pin
				results[i] = r
				return
			}
			h := probeStore(self, t.name, t.entry, timeout)
			switch {
			case h.Status == "fail":
				r.Status, r.Reason = "fail", "wrapper does not resolve a database: "+h.Reason
			case h.Probe != "wrapper":
				r.Status, r.Reason = "fail", "wrapper not executable after rewrite"
			case !t.classified:
				r.Status = "unclassified"
				r.Reason = "no readable .beads/metadata.json and no baked host pin, so the wrapper was not repointed"
			default:
				r.Status = "ok"
			}
			results[i] = r
		}(i, t)
	}
	wg.Wait()
	return results
}

func failedRewrites(rs []wrapperRewrite) []wrapperRewrite {
	var out []wrapperRewrite
	for _, r := range rs {
		if r.Status != "ok" {
			out = append(out, r)
		}
	}
	return out
}

var brainStoresRewriteWrappersCmd = &cobra.Command{
	Use:   "rewrite-wrappers",
	Short: "Make every store/alias CLI wrapper $HOME-relative, resolve the Dolt host from the shared config, and verify each resolves a database",
	Long: `Rewrites the BEADS_DIR and BRAIN_KNOWLEDGE_ROOT lines of each existing
~/.local/bin wrapper (registered stores and 'brain stores alias' wrappers) to
"$HOME/\u2026" in place, preserving every other line. A server-mode store's
wrapper is also repointed at the shared store host config
(~/.config/brain/store-host.env): the run-time host block is installed before
the wrapper's first bd invocation path (never only above the final exec) and
any whole-line baked BEADS_DOLT_SERVER_HOST/PORT pin is dropped. A wrapper that
still contains a host or port assignment the verb cannot safely rewrite is
reported as failed, not verified. Each rewritten wrapper is first copied to
<wrapper>.bak, so the repoint can be rolled back.

The shared file must already exist: this verb refuses up front rather than
repointing the fleet into wrappers that would refuse every invocation. Embedded
stores keep their minimal wrapper, and forwarding wrappers installed by 'brain
remote install' are left alone. Registry entries are left exactly as recorded:
an entry whose path names another machine's home is reported by 'brain stores
doctor'. Stores with no wrapper are skipped. Each wrapper is then read through
the way 'brain stores doctor' does.

This is the one step that repoints a host's stores at the federation's shared
server. It prints what it changed.

Exits non-zero, naming every store that failed, if any wrapper cannot be
written or does not resolve a database. 'brain remote set' and
'brain remote install' run this on the brain host.`,
	Args: cobra.NoArgs,
	Run: func(cmd *cobra.Command, _ []string) {
		// The block this verb installs reads the shared store host config at run
		// time and refuses without it, so require the file before any wrapper is
		// touched: repointing first would leave every store's CLI refusing.
		path := configfile.DefaultStoreHostPath()
		if path == "" {
			path = "~/.config/brain/" + configfile.StoreHostFileName
		}
		if _, err := os.Stat(path); err != nil {
			FatalError("shared store host config %s does not exist: write %s=<host> and %s=<port> there before repointing wrappers, then re-run",
				path, configfile.StoreHostKeyHost, configfile.StoreHostKeyPort)
		}
		if err := configfile.ValidateStoreHostFile(); err != nil {
			FatalError("%v", err)
		}

		stores, err := loadStoresRegistry()
		if err != nil {
			FatalError("loading registry: %v", err)
		}
		self, err := os.Executable()
		if err != nil || self == "" {
			self = os.Args[0]
		}
		results := rewriteAllStoreWrappers(self, stores, storesRewriteJobs, storesRewriteTimeout)
		failed := failedRewrites(results)
		repointed := 0
		for _, r := range results {
			if r.Repointed {
				repointed++
			}
		}
		if jsonOutput {
			outputJSON(map[string]any{"total": len(results), "failed": len(failed), "repointed": repointed, "stores": results})
		} else {
			for _, r := range results {
				switch r.Status {
				case "ok":
					note := ""
					if r.Repointed {
						note = "  (host now read from the shared store host config)"
					}
					fmt.Printf("  ok    %-18s %s%s\n", r.Name, r.Wrapper, note)
				case "unclassified":
					fmt.Printf("  WARN  %-18s %s\n", r.Name, r.Reason)
				default:
					fmt.Printf("  FAIL  %-18s %s\n", r.Name, r.Reason)
				}
			}
			if len(failed) == 0 {
				fmt.Printf("%d/%d wrappers rewritten and verified (%d repointed at the shared store host config)\n",
					len(results), len(results), repointed)
			} else {
				fmt.Printf("%d/%d wrappers rewritten; %d not verified — see above\n",
					len(results)-len(failed), len(results), len(failed))
			}
		}
		if len(failed) > 0 {
			var n []string
			for _, r := range failed {
				n = append(n, r.Name)
			}
			sort.Strings(n)
			fmt.Fprintf(os.Stderr, "FAILING STORES: %s\n", strings.Join(n, " "))
			os.Exit(1)
		}
	},
}

// verifyHostWrappers runs 'brain stores rewrite-wrappers' on the host and
// returns an error listing every store whose wrapper failed. It is the gate
// behind 'brain remote set' and 'brain remote install': a host whose wrappers
// cannot resolve a database must not look successfully configured.
func verifyHostWrappers(ctx context.Context, cfg *remoteConfig) (total int, err error) {
	out, runErr := remoteCapture(ctx, cfg, "brain", "stores", "rewrite-wrappers", "--json")
	results, perr := parseRewriteResults(out)
	if perr != nil {
		if runErr != nil {
			return 0, fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, runErr)
		}
		return 0, fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, perr)
	}
	if failed := failedRewrites(results); len(failed) > 0 {
		var b strings.Builder
		fmt.Fprintf(&b, "%d of %d store wrappers on %s did not pass the repoint/verify pass:", len(failed), len(results), cfg.Host)
		for _, r := range failed {
			fmt.Fprintf(&b, "\n  %s: %s", r.Name, r.Reason)
		}
		return len(results), fmt.Errorf("%s", b.String())
	}
	if runErr != nil {
		return len(results), fmt.Errorf("rewriting wrappers on %s: %w", cfg.Host, runErr)
	}
	return len(results), nil
}

func parseRewriteResults(data []byte) ([]wrapperRewrite, error) {
	start := strings.Index(string(data), "{")
	if start < 0 {
		return nil, fmt.Errorf("host printed no JSON result: %q", strings.TrimSpace(string(data)))
	}
	var payload struct {
		Stores []wrapperRewrite `json:"stores"`
	}
	if err := json.Unmarshal(data[start:], &payload); err != nil {
		return nil, fmt.Errorf("parsing host result: %w", err)
	}
	return payload.Stores, nil
}

