package main

// The proxied-server capability rows for brain's own commands.
//
// Every runnable command needs a row (TestProxyCapabilityRegistryCoversCommandTree).
// Brain stores live on a shared Dolt server reached in server mode; no brain
// host runs a proxied-server workspace, and none of brain's verbs has a route
// over the proxied provider. A typed refusal at the front door is the honest
// answer there, and it stops the root pre-run from starting a proxy only for
// the command to fail at the store factory. Each row is "unimplemented"
// rather than "design": nothing about the proxied topology makes these wrong,
// nobody has needed them there.
const trackBrainProxied = "brain on the proxied provider: brain stores run in server mode, so no brain verb is routed over a proxied-server workspace"

func brainRefusal(path string) capabilityRow {
	return refusedPath(path, "proxy.brain.unsupported", ProxyReasonUnimplemented, trackBrainProxied)
}

